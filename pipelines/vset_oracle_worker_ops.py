"""Piece of the candidate worker program.

The grader concatenates the pieces. Nothing under the worktree can replace them.
"""

from __future__ import annotations

import sys

if __package__:  # pragma: no cover - package-child import path
    from . import _assert_direct_sibling, _expose_package_sibling

    _assert_direct_sibling("vset_oracle_worker_ops")
else:
    getattr(sys.modules.get("pipelines"), "_join_package_sibling", lambda name: None)(
        "vset_oracle_worker_ops"
    )


WORKER_OPS = (
    'def mapped(pairs):\n',
    '    return {decode(pair[0]): decode(pair[1]) for pair in pairs}\n',
    '\n',
    '\n',
    'def remember_slot(value, decoded):\n',
    '    if value.get("slot") is not None:\n',
    '        slots[value["slot"]] = decoded\n',
    '    return decoded\n',
    '\n',
    '\n',
    'def rebuild_path(name, text):\n',
    '    cls = getattr(__import__("pathlib"), str(name or ""), None)\n',
    '    if not isinstance(cls, type):\n',
    '        return PurePath(text)\n',
    '    return cls(text)\n',
    '\n',
    '\n',
    'def rebuild_namedtuple(value):\n',
    '    fields = tuple(value.get("fields") or ())\n',
    '    key = (str(value.get("namedtuple")), fields)\n',
    '    if key not in _NT:\n',
    '        _NT[key] = namedtuple(key[0], fields)\n',
    '    return _NT[key](*(decode(item) for item in value.get("items") or ()))\n',
    '\n',
    '\n',
    'def snapshot(value):\n',
    '    if value is None or isinstance(value, (bool, int, float, str)):\n',
    '        return {"kind": "value", "value": value}\n',
    '    if type(value) is list:\n',
    '        return {"kind": "list", "items": [snapshot(item) for item in value]}\n',
    '    if type(value) is dict:\n',
    '        pairs = [[snapshot(key), snapshot(item)] for key, item in value.items()]\n',
    '        return {"kind": "dict", "items": pairs}\n',
    '    if type(value) is set:\n',
    '        return {"kind": "set", "items": [snapshot(item) for item in value]}\n',
    '    if type(value) is bytearray:\n',
    '        data = base64.b64encode(bytes(value)).decode("ascii")\n',
    '        return {"kind": "bytes", "data": data}\n',
    '    return put(value)\n',
    '\n',
    '\n',
    'def reply(payload):\n',
    '    real_out.write(json.dumps(payload) + "\\n")\n',
    '    real_out.flush()\n',
    '\n',
    '\n',
    '_MISSING = object()\n',
    '_PATCHES = {}\n',
    '\n',
    '\n',
    'class ParentProxy:\n',
    '    def __init__(self, cb):\n',
    '        self._cb = cb\n',
    '\n',
    '    def __setattr__(self, name, value):\n',
    '        if name == "_cb":\n',
    '            object.__setattr__(self, name, value)\n',
    '            return\n',
    '        ask({\n',
    '            "kind": "callback",\n',
    '            "op": "set",\n',
    '            "cb": self._cb,\n',
    '            "attr": name,\n',
    '            "value": put(value),\n',
    '        })\n',
    '\n',
    '    def __call__(self, *args, **kwargs):\n',
    '        return ask({\n',
    '            "kind": "callback",\n',
    '            "op": "call",\n',
    '            "cb": self._cb,\n',
    '            "args": [put(arg) for arg in args],\n',
    '            "kwargs": {key: put(val) for key, val in kwargs.items()},\n',
    '        })\n',
    '\n',
    '    def __getattr__(self, name):\n',
    '        return ask({\n',
    '            "kind": "callback",\n',
    '            "op": "get",\n',
    '            "cb": self._cb,\n',
    '            "attr": name,\n',
    '        })\n',
    '\n',
    '    def _dunder(self, name, *args):\n',
    '        method = ask({\n',
    '            "kind": "callback",\n',
    '            "op": "get",\n',
    '            "cb": self._cb,\n',
    '            "attr": name,\n',
    '        })\n',
    '        return method(*args)\n',
    '\n',
    '    def __iter__(self):\n',
    '        return self._dunder("__iter__")\n',
    '\n',
    '    def __next__(self):\n',
    '        return self._dunder("__next__")\n',
    '\n',
    '    def __len__(self):\n',
    '        try:\n',
    '            return self._dunder("__len__")\n',
    '        except AttributeError:\n',
    '            raise TypeError("object has no len()")\n',
    '\n',
    '    def __getitem__(self, key):\n',
    '        return self._dunder("__getitem__", key)\n',
    '\n',
    '    def __contains__(self, item):\n',
    '        return self._dunder("__contains__", item)\n',
    '\n',
    '\n',
    'def ask(payload):\n',
    '    reply(payload)\n',
    '    while True:\n',
    '        line = sys.stdin.readline()\n',
    '        if not line:\n',
    '            raise EOFError("oracle worker exited")\n',
    '        req = json.loads(line)\n',
    '        if "cb_result" not in req:\n',
    '            handle(req)\n',
    '            continue\n',
    '        if req.get("ok"):\n',
    '            return decode(req.get("value"))\n',
    '        raise rebuild_callback(req)\n',
    '\n',
    '\n',
    'def builtin_exc(name):\n',
    '    found = getattr(builtins, name, None)\n',
    '    if not isinstance(found, type):\n',
    '        return None\n',
    '    try:\n',
    '        if issubclass(found, Exception):\n',
    '            return found\n',
    '    except TypeError:\n',
    '        return None\n',
    '    return None\n',
    '\n',
    '\n',
    'def make_exc(name, chain):\n',
    '    found = builtin_exc(name)\n',
    '    if found is not None:\n',
    '        return found\n',
    '    key = (name, tuple(chain))\n',
    '    if key in _EXC:\n',
    '        return _EXC[key]\n',
    '    base = Exception\n',
    '    if chain:\n',
    '        base = make_exc(chain[0], chain[1:])\n',
    '    created = type(name, (base,), {})\n',
    '    _EXC[key] = created\n',
    '    return created\n',
    '\n',
    '\n',
    'def rebuild_callback(req):\n',
    '    name = str(req.get("type") or "RuntimeError")\n',
    '    raw = req.get("chain") or ["Exception"]\n',
    '    chain = [str(item) for item in raw]\n',
    '    args = req.get("args")\n',
    '    if not isinstance(args, list):\n',
    '        args = [req.get("message", "")]\n',
    '    return make_exc(name, chain)(*(decode(arg) for arg in args))\n',
    '\n',
    '\n',
    'def ask_method(cb, name, owner, args, kwargs):\n',
    '    sent = {"kind": "value", "value": None}\n',
    '    if owner is not None:\n',
    '        sent = put(owner)\n',
    '    return ask({\n',
    '        "kind": "callback",\n',
    '        "op": "call",\n',
    '        "cb": cb,\n',
    '        "args": [put(name), sent, put(args), put(kwargs)],\n',
    '        "kwargs": {},\n',
    '    })\n',
    '\n',
    '\n',
    'def bind_named(cb, spec):\n',
    '    name = str(spec["name"])\n',
    '    kind = str(spec.get("kind") or "func")\n',
    '    if kind == "prop":\n',
    '        def getter(self):\n',
    '            return ask_method(cb, name, self, (), {})\n',
    '        return property(getter)\n',
    '    if kind == "static":\n',
    '        def fn(*args, **kwargs):\n',
    '            return ask_method(cb, name, None, args, kwargs)\n',
    '        return staticmethod(fn)\n',
    '    if kind == "class":\n',
    '        def fn(cls, *args, **kwargs):\n',
    '            return ask_method(cb, name, None, args, kwargs)\n',
    '        return classmethod(fn)\n',
    '    def method(self, *args, **kwargs):\n',
    '        return ask_method(cb, name, self, args, kwargs)\n',
    '    return method\n',
    '\n',
    '\n',
    'def finish(result):\n',
    '    states = []\n',
    '    for slot, obj in slots.items():\n',
    '        states.append({"slot": slot, "state": snapshot(obj)})\n',
    '    slots.clear()\n',
    '    return {"kind": "synced", "value": put(result), "states": states}\n',
    '\n',
    '\n',
    'def handle(req):\n',
    '    try:\n',
    '        out = run_op(req)\n',
    '    except Exception as exc:\n',
    '        attrs = {}\n',
    '        for key, val in getattr(exc, "__dict__", {}).items():\n',
    '            attrs[key] = put(val)\n',
    '        out = {\n',
    '            "kind": "error",\n',
    '            "exc": describe_exc(type(exc)),\n',
    '            "type": type(exc).__name__,\n',
    '            "chain": exc_chain(type(exc)),\n',
    '            "args": [put(arg) for arg in exc.args],\n',
    '            "attrs": attrs,\n',
    '        }\n',
    '    reply(out)\n',
    '\n',
    '\n',
    'def run_op(req):\n',
    '    op = req["op"]\n',
    '    if op == "import":\n',
    '        return put(importlib.import_module(req["name"]))\n',
    '    if op == "get":\n',
    '        return put(getattr(objs[req["oid"]], req["attr"]))\n',
    '    if op == "set":\n',
    '        setattr(objs[req["oid"]], req["attr"], decode(req["value"]))\n',
    '        return {"kind": "value", "value": None}\n',
    '    if op == "del":\n',
    '        delattr(objs[req["oid"]], req["attr"])\n',
    '        return {"kind": "value", "value": None}\n',
    '    if op == "patch":\n',
    '        mod = importlib.import_module(req["name"])\n',
    '        attr = req["attr"]\n',
    '        old = _MISSING\n',
    '        if hasattr(mod, attr):\n',
    '            old = getattr(mod, attr)\n',
    '        _PATCHES[req["token"]] = (mod, attr, old)\n',
    '        setattr(mod, attr, decode(req["value"]))\n',
    '        return {"kind": "value", "value": None}\n',
    '    if op == "unpatch":\n',
    '        mod, attr, old = _PATCHES.pop(req["token"])\n',
    '        if old is _MISSING:\n',
    '            delattr(mod, attr)\n',
    '        else:\n',
    '            setattr(mod, attr, old)\n',
    '        return {"kind": "value", "value": None}\n',
    '    if op == "environ":\n',
    '        for key in req["drop"]:\n',
    '            os.environ.pop(key, None)\n',
    '        os.environ.update(req["set"])\n',
    '        return {"kind": "value", "value": None}\n',
    '    if op == "call":\n',
    '        args = [decode(arg) for arg in req["args"]]\n',
    '        kwargs = {key: decode(val) for key, val in req["kwargs"].items()}\n',
    '        result = objs[req["oid"]](*args, **kwargs)\n',
    '        return finish(result)\n',
    '    if op == "alloc":\n',
    '        cls = objs[req["oid"]]\n',
    '        try:\n',
    '            obj = cls.__new__(cls)\n',
    '        except TypeError:\n',
    '            args = [decode(item) for item in req.get("args") or []]\n',
    '            kwargs = {\n',
    '                key: decode(val) for key, val in (req.get("kwargs") or {}).items()\n',
    '            }\n',
    '            obj = cls.__new__(cls, *args, **kwargs)\n',
    '        return put(obj)\n',
    '    if op == "init":\n',
    '        obj = objs[req["oid"]]\n',
    '        base = objs[req["base"]]\n',
    '        args = [decode(item) for item in req.get("args") or []]\n',
    '        kwargs = {\n',
    '            key: decode(val) for key, val in (req.get("kwargs") or {}).items()\n',
    '        }\n',
    '        base.__init__(obj, *args, **kwargs)\n',
    '        return finish(None)\n',
    '    if op == "subclass":\n',
    '        base = objs[req["base"]]\n',
    '        body = {}\n',
    '        for spec in req.get("methods") or []:\n',
    '            body[str(spec["name"])] = bind_named(req["cb"], spec)\n',
    '        for name, value in (req.get("attrs") or {}).items():\n',
    '            body[str(name)] = decode(value)\n',
    '        created = type(str(req["name"]), (base,), body)\n',
    '        return put(created)\n',
    '    return {\n',
    '        "kind": "error",\n',
    '        "type": "RuntimeError",\n',
    '        "chain": ["Exception"],\n',
    '        "message": "bad op",\n',
    '    }\n',
    '\n',
    '\n',
    'class _Out:\n',
    '    def write(self, text):\n',
    '        if text:\n',
    '            reply({"kind": "stdout", "text": text})\n',
    '        return len(text or "")\n',
    '\n',
    '    def flush(self):\n',
    '        return None\n',
    '\n',
    '\n',
    'class _Log(logging.Handler):\n',
    '    def emit(self, record):\n',
    '        reply({\n',
    '            "kind": "log",\n',
    '            "name": record.name,\n',
    '            "level": record.levelno,\n',
    '            "msg": record.getMessage(),\n',
    '        })\n',
    '\n',
    '\n',
    'sys.stdout = _Out()\n',
    'logging.getLogger().addHandler(_Log())\n',
    'logging.getLogger().setLevel(1)\n',
    '\n',
    'while True:\n',
    '    line = sys.stdin.readline()\n',
    '    if not line:\n',
    '        break\n',
    '    if not line.strip():\n',
    '        continue\n',
    '    handle(json.loads(line))\n',
)
WORKER_OPS = ''.join(WORKER_OPS)

if __package__:  # pragma: no cover - package-child import path
    _expose_package_sibling(__name__)
