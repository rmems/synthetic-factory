WORKER_OPS = (
    'def mapped(pairs):\n',
    '    return {decode(pair[0]): decode(pair[1]) for pair in pairs}\n',
    '\n',
    '\n',
    'def remember_slot(value, decoded):\n',
    '    if value.get("slot") is not None:\n',
    '        slots[value["slot"]] = decoded\n',
    '    return decoded\n',
    '\n',
    '\n',
    'def rebuild_path(name, text):\n',
    '    cls = getattr(__import__("pathlib"), str(name or ""), None)\n',
    '    if not isinstance(cls, type):\n',
    '        return PurePath(text)\n',
    '    return cls(text)\n',
    '\n',
    '\n',
    'def rebuild_namedtuple(value):\n',
    '    fields = tuple(value.get("fields") or ())\n',
    '    key = (str(value.get("namedtuple")), fields)\n',
    '    if key not in _NT:\n',
    '        _NT[key] = namedtuple(key[0], fields)\n',
    '    return _NT[key](*(decode(item) for item in value.get("items") or ()))\n',
    '\n',
    '\n',
    'def snapshot(value):\n',
    '    if value is None or isinstance(value, (bool, int, float, str)):\n',
    '        return {"kind": "value", "value": value}\n',
    '    if type(value) is list:\n',
    '        return {"kind": "list", "items": [snapshot(item) for item in value]}\n',
    '    if type(value) is dict:\n',
    '        pairs = [[snapshot(key), snapshot(item)] for key, item in value.items()]\n',
    '        return {"kind": "dict", "items": pairs}\n',
    '    if type(value) is set:\n',
    '        return {"kind": "set", "items": [snapshot(item) for item in value]}\n',
    '    if type(value) is bytearray:\n',
    '        data = base64.b64encode(bytes(value)).decode("ascii")\n',
    '        return {"kind": "bytes", "data": data}\n',
    '    return put(value)\n',
    '\n',
    '\n',
    '_CHUNK = 100000\n',
    '\n',
    '\n',
    'def reply(payload):\n',
    '    text = json.dumps(payload)\n',
    '    if len(text) <= _CHUNK:\n',
    '        real_out.write(text + "\\n")\n',
    '        real_out.flush()\n',
    '        return\n',
    '    parts = [text[index:index + _CHUNK] for index in range(0, len(text), _CHUNK)]\n',
    '    real_out.write(json.dumps({"kind": "span", "n": len(parts)}) + "\\n")\n',
    '    for part in parts:\n',
    '        real_out.write(json.dumps({"kind": "span", "data": part}) + "\\n")\n',
    '    real_out.flush()\n',
    '\n',
    '\n',
    '_MISSING = object()\n',
    '_PATCHES = {}\n',
    '\n',
    '\n',
    'class ParentProxy:\n',
    '    def __init__(self, cb):\n',
    '        self._cb = cb\n',
    '\n',
    '    def __setattr__(self, name, value):\n',
    '        if name == "_cb":\n',
    '            object.__setattr__(self, name, value)\n',
    '            return\n',
    '        ask({\n',
    '            "kind": "callback",\n',
    '            "op": "set",\n',
    '            "cb": self._cb,\n',
    '            "attr": name,\n',
    '            "value": put(value),\n',
    '        })\n',
    '\n',
    '    def __call__(self, *args, **kwargs):\n',
    '        return ask({\n',
    '            "kind": "callback",\n',
    '            "op": "call",\n',
    '            "cb": self._cb,\n',
    '            "args": [put(arg) for arg in args],\n',
    '            "kwargs": {key: put(val) for key, val in kwargs.items()},\n',
    '        })\n',
    '\n',
    '    def __getattr__(self, name):\n',
    '        return ask({\n',
    '            "kind": "callback",\n',
    '            "op": "get",\n',
    '            "cb": self._cb,\n',
    '            "attr": name,\n',
    '        })\n',
    '\n',
    '    def _dunder(self, name, *args):\n',
    '        method = ask({\n',
    '            "kind": "callback",\n',
    '            "op": "get",\n',
    '            "cb": self._cb,\n',
    '            "attr": name,\n',
    '        })\n',
    '        return method(*args)\n',
    '\n',
    '    def __iter__(self):\n',
    '        return self._dunder("__iter__")\n',
    '\n',
    '    def __next__(self):\n',
    '        return self._dunder("__next__")\n',
    '\n',
    '    def __len__(self):\n',
    '        try:\n',
    '            return self._dunder("__len__")\n',
    '        except AttributeError:\n',
    '            raise TypeError("object has no len()")\n',
    '\n',
    '    def __getitem__(self, key):\n',
    '        return self._dunder("__getitem__", key)\n',
    '\n',
    '    def __contains__(self, item):\n',
    '        return self._dunder("__contains__", item)\n',
    '\n',
    '\n',
    'def ask(payload):\n',
    '    reply(payload)\n',
    '    while True:\n',
    '        line = sys.stdin.readline()\n',
    '        if not line:\n',
    '            raise EOFError("oracle worker exited")\n',
    '        req = json.loads(line)\n',
    '        if "cb_result" not in req:\n',
    '            handle(req)\n',
    '            continue\n',
    '        if req.get("ok"):\n',
    '            return decode(req.get("value"))\n',
    '        raise rebuild_callback(req)\n',
    '\n',
    '\n',
    'def builtin_exc(name):\n',
    '    found = getattr(builtins, name, None)\n',
    '    if not isinstance(found, type):\n',
    '        return None\n',
    '    try:\n',
    '        if issubclass(found, Exception):\n',
    '            return found\n',
    '    except TypeError:\n',
    '        return None\n',
    '    return None\n',
    '\n',
    '\n',
    'def make_exc(name, chain):\n',
    '    found = builtin_exc(name)\n',
    '    if found is not None:\n',
    '        return found\n',
    '    key = (name, tuple(chain))\n',
    '    if key in _EXC:\n',
    '        return _EXC[key]\n',
    '    base = Exception\n',
    '    if chain:\n',
    '        base = make_exc(chain[0], chain[1:])\n',
    '    created = type(name, (base,), {})\n',
    '    _EXC[key] = created\n',
    '    return created\n',
    '\n',
    '\n',
    'def rebuild_callback(req):\n',
    '    name = str(req.get("type") or "RuntimeError")\n',
    '    raw = req.get("chain") or ["Exception"]\n',
    '    chain = [str(item) for item in raw]\n',
    '    args = req.get("args")\n',
    '    if not isinstance(args, list):\n',
    '        args = [req.get("message", "")]\n',
    '    return make_exc(name, chain)(*(decode(arg) for arg in args))\n',
    '\n',
    '\n',
    'def ask_method(cb, name, owner, args, kwargs):\n',
    '    sent = {"kind": "value", "value": None}\n',
    '    if owner is not None:\n',
    '        sent = put(owner)\n',
    '    return ask({\n',
    '        "kind": "callback",\n',
    '        "op": "call",\n',
    '        "cb": cb,\n',
    '        "args": [put(name), sent, put(args), put(kwargs)],\n',
    '        "kwargs": {},\n',
    '    })\n',
    '\n',
    '\n',
    'def bind_named(cb, spec):\n',
    '    name = str(spec["name"])\n',
    '    kind = str(spec.get("kind") or "func")\n',
    '    if kind == "prop":\n',
    '        def getter(self):\n',
    '            return ask_method(cb, name, self, (), {})\n',
    '        return property(getter)\n',
    '    if kind == "static":\n',
    '        def fn(*args, **kwargs):\n',
    '            return ask_method(cb, name, None, args, kwargs)\n',
    '        return staticmethod(fn)\n',
    '    if kind == "class":\n',
    '        def fn(cls, *args, **kwargs):\n',
    '            return ask_method(cb, name, None, args, kwargs)\n',
    '        return classmethod(fn)\n',
    '    def method(self, *args, **kwargs):\n',
    '        return ask_method(cb, name, self, args, kwargs)\n',
    '    return method\n',
    '\n',
    '\n',
    '_ENV = []\n',
    '\n',
    '\n',
    'def apply_environ(req):\n',
    '    if req.get("undo"):\n',
    '        if _ENV:\n',
    '            saved = _ENV.pop()\n',
    '            for key, old in saved:\n',
    '                if old is None:\n',
    '                    os.environ.pop(key, None)\n',
    '                else:\n',
    '                    os.environ[key] = old\n',
    '        return {"kind": "value", "value": None}\n',
    '    keys = list(req.get("set") or {}) + list(req.get("drop") or [])\n',
    '    saved = []\n',
    '    for key in keys:\n',
    '        if key in os.environ:\n',
    '            saved.append([key, os.environ[key]])\n',
    '        else:\n',
    '            saved.append([key, None])\n',
    '    _ENV.append(saved)\n',
    '    for key in req.get("drop") or []:\n',
    '        os.environ.pop(key, None)\n',
    '    os.environ.update(req.get("set") or {})\n',
    '    return {"kind": "value", "value": None}\n',
    '\n',
    '\n',
    'def _plain_value(val):\n',
    '    if val is None:\n',
    '        return True\n',
    '    return type(val) in (bool, int, float, str, bytes)\n',
    '\n',
    '\n',
    'def _keep_key(key):\n',
    '    if not isinstance(key, str):\n',
    '        return False\n',
    '    if key.startswith("__"):\n',
    '        return False\n',
    '    return True\n',
    '\n',
    '\n',
    'def _read_dict(obj):\n',
    '    try:\n',
    '        raw = object.__getattribute__(obj, "__dict__")\n',
    '    except Exception:\n',
    '        return {}\n',
    '    if isinstance(raw, dict):\n',
    '        return raw\n',
    '    return {}\n',
    '\n',
    '\n',
    'def _slot_names(obj):\n',
    '    names = []\n',
    '    for cls in type(obj).__mro__:\n',
    '        raw = cls.__dict__.get("__slots__")\n',
    '        if isinstance(raw, str):\n',
    '            names.append(raw)\n',
    '            continue\n',
    '        if isinstance(raw, (tuple, list)):\n',
    '            names.extend(raw)\n',
    '    return names\n',
    '\n',
    '\n',
    'def _remember(found, key, val):\n',
    '    if not _keep_key(key):\n',
    '        return\n',
    '    if key in found:\n',
    '        return\n',
    '    if _plain_value(val):\n',
    '        found[key] = val\n',
    '\n',
    '\n',
    'def plain_fields(obj):\n',
    '    found = {}\n',
    '    for key, val in _read_dict(obj).items():\n',
    '        _remember(found, key, val)\n',
    '    for name in _slot_names(obj):\n',
    '        try:\n',
    '            val = object.__getattribute__(obj, name)\n',
    '        except Exception:\n',
    '            continue\n',
    '        _remember(found, name, val)\n',
    '    return found\n',
    '\n',
    '\n',
    'def _user_function(found):\n',
    '    if isinstance(found, (staticmethod, classmethod)):\n',
    '        found = found.__func__\n',
    '    code = getattr(found, "__code__", None)\n',
    '    if code is None:\n',
    '        return False\n',
    '    filename = str(code.co_filename)\n',
    '    if filename.startswith("<frozen"):\n',
    '        return False\n',
    '    if filename.startswith(sys.base_prefix):\n',
    '        return False\n',
    '    return True\n',
    '\n',
    '\n',
    'def user_compares(obj):\n',
    '    names = []\n',
    '    checked = ("__eq__", "__ne__", "__lt__", "__le__", "__gt__", "__ge__")\n',
    '    for name in checked:\n',
    '        found = None\n',
    '        for cls in type(obj).__mro__:\n',
    '            if name in cls.__dict__:\n',
    '                found = cls.__dict__[name]\n',
    '                break\n',
    '        if _user_function(found):\n',
    '            names.append(name)\n',
    '    return names\n',
    '\n',
    '\n',
    'def object_state(obj):\n',
    '    fields = plain_fields(obj)\n',
    '    encoded = {key: put(val) for key, val in fields.items()}\n',
    '    return {"kind": "state", "fields": encoded, "user": user_compares(obj)}\n',
    '\n',
    '\n',
    'def _note_state(states, seen, slot, obj):\n',
    '    if slot is None:\n',
    '        return\n',
    '    if slot in seen:\n',
    '        return\n',
    '    seen.add(slot)\n',
    '    states.append({"slot": slot, "state": snapshot(obj)})\n',
    '\n',
    '\n',
    'def slot_states():\n',
    '    states = []\n',
    '    seen = set()\n',
    '    for slot, obj in list(slots.items()):\n',
    '        _note_state(states, seen, slot, obj)\n',
    '    slots.clear()\n',
    '    for obj in _PINNED:\n',
    '        _note_state(states, seen, _ALIAS.get(id(obj)), obj)\n',
    '    return states\n',
    '\n',
    '\n',
    'def finish(result):\n',
    '    return {"kind": "synced", "value": put(result), "states": slot_states()}\n',
    '\n',
    '\n',
    'def handle(req):\n',
    '    try:\n',
    '        out = run_op(req)\n',
    '    except Exception as exc:\n',
    '        attrs = {}\n',
    '        for key, val in getattr(exc, "__dict__", {}).items():\n',
    '            attrs[key] = put(val)\n',
    '        out = {\n',
    '            "kind": "error",\n',
    '            "exc": describe_exc(type(exc)),\n',
    '            "type": type(exc).__name__,\n',
    '            "chain": exc_chain(type(exc)),\n',
    '            "args": [put(arg) for arg in exc.args],\n',
    '            "attrs": attrs,\n',
    '            "states": slot_states(),\n',
    '        }\n',
    '    reply(out)\n',
    '\n',
    '\n',
    'def run_op(req):\n',
    '    op = req["op"]\n',
    '    if op == "import":\n',
    '        return put(importlib.import_module(req["name"]))\n',
    '    if op == "get":\n',
    '        return put(getattr(objs[req["oid"]], req["attr"]))\n',
    '    if op == "set":\n',
    '        setattr(objs[req["oid"]], req["attr"], decode(req["value"]))\n',
    '        return {"kind": "value", "value": None}\n',
    '    if op == "del":\n',
    '        delattr(objs[req["oid"]], req["attr"])\n',
    '        return {"kind": "value", "value": None}\n',
    '    if op == "patch":\n',
    '        mod = importlib.import_module(req["name"])\n',
    '        attr = req["attr"]\n',
    '        old = _MISSING\n',
    '        if hasattr(mod, attr):\n',
    '            old = getattr(mod, attr)\n',
    '        _PATCHES[req["token"]] = (mod, attr, old)\n',
    '        setattr(mod, attr, decode(req["value"]))\n',
    '        return {"kind": "value", "value": None}\n',
    '    if op == "unpatch":\n',
    '        mod, attr, old = _PATCHES.pop(req["token"])\n',
    '        if old is _MISSING:\n',
    '            delattr(mod, attr)\n',
    '        else:\n',
    '            setattr(mod, attr, old)\n',
    '        return {"kind": "value", "value": None}\n',
    '    if op == "environ":\n',
    '        return apply_environ(req)\n',
    '    if op == "state":\n',
    '        return object_state(objs[req["oid"]])\n',
    '    if op == "call":\n',
    '        args = [decode(arg) for arg in req["args"]]\n',
    '        kwargs = {key: decode(val) for key, val in req["kwargs"].items()}\n',
    '        result = objs[req["oid"]](*args, **kwargs)\n',
    '        return finish(result)\n',
    '    if op == "alloc":\n',
    '        cls = objs[req["oid"]]\n',
    '        try:\n',
    '            obj = cls.__new__(cls)\n',
    '        except TypeError:\n',
    '            args = [decode(item) for item in req.get("args") or []]\n',
    '            kwargs = {\n',
    '                key: decode(val) for key, val in (req.get("kwargs") or {}).items()\n',
    '            }\n',
    '            obj = cls.__new__(cls, *args, **kwargs)\n',
    '        return put(obj)\n',
    '    if op == "init":\n',
    '        obj = objs[req["oid"]]\n',
    '        base = objs[req["base"]]\n',
    '        args = [decode(item) for item in req.get("args") or []]\n',
    '        kwargs = {\n',
    '            key: decode(val) for key, val in (req.get("kwargs") or {}).items()\n',
    '        }\n',
    '        base.__init__(obj, *args, **kwargs)\n',
    '        return finish(None)\n',
    '    if op == "subclass":\n',
    '        base = objs[req["base"]]\n',
    '        body = {}\n',
    '        for spec in req.get("methods") or []:\n',
    '            body[str(spec["name"])] = bind_named(req["cb"], spec)\n',
    '        for name, value in (req.get("attrs") or {}).items():\n',
    '            body[str(name)] = decode(value)\n',
    '        created = type(str(req["name"]), (base,), body)\n',
    '        return put(created)\n',
    '    return {\n',
    '        "kind": "error",\n',
    '        "type": "RuntimeError",\n',
    '        "chain": ["Exception"],\n',
    '        "message": "bad op",\n',
    '    }\n',
    '\n',
    '\n',
    'class _Out:\n',
    '    def write(self, text):\n',
    '        if text:\n',
    '            reply({"kind": "stdout", "text": text})\n',
    '        return len(text or "")\n',
    '\n',
    '    def flush(self):\n',
    '        return None\n',
    '\n',
    '\n',
    'class _Log(logging.Handler):\n',
    '    def emit(self, record):\n',
    '        reply({\n',
    '            "kind": "log",\n',
    '            "name": record.name,\n',
    '            "level": record.levelno,\n',
    '            "msg": record.getMessage(),\n',
    '        })\n',
    '\n',
    '\n',
    'sys.stdout = _Out()\n',
    'logging.getLogger().addHandler(_Log())\n',
    'logging.getLogger().setLevel(1)\n',
    '\n',
    'while True:\n',
    '    line = sys.stdin.readline()\n',
    '    if not line:\n',
    '        break\n',
    '    if not line.strip():\n',
    '        continue\n',
    '    handle(json.loads(line))\n',
)
WORKER_OPS = ''.join(WORKER_OPS)

