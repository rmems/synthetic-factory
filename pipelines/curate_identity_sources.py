#!/usr/bin/env python3
"""Source coordinates, record classification, and canonical identity.

Split out of ``curate_identity.py`` (CodeScene: Lines of Code in a Single
File) by responsibility; every name is re-exported from ``curate_identity``
so existing ``curate_identity.X`` call sites and test seams resolve
unchanged.

The immutable ``SourceRecord`` coordinate and the ``SourceIdentity`` derived
from it anchor canonical ID preimages.  Payload shape classification and
factory declarations are read here without granting registry authority; the
reviewed registry decides whether a declared factory may emit records.
"""

from __future__ import annotations

import hashlib
import sys
from dataclasses import dataclass
from pathlib import PurePosixPath
from typing import Any, Mapping

if __package__:
    from . import _assert_direct_sibling, _expose_package_sibling

    _assert_direct_sibling("curate_identity_sources")
    from . import curate_identity_checks as _identity_checks
    from . import curate_identity_json as _identity_json
    from .record_kind import PRESERVED_NATIVE_KINDS, classify_kind
else:
    getattr(sys.modules.get("pipelines"), "_join_package_sibling", lambda name: None)(
        "curate_identity_sources"
    )
    import curate_identity_checks as _identity_checks
    import curate_identity_json as _identity_json
    from record_kind import PRESERVED_NATIVE_KINDS, classify_kind

IdentityCurationError = _identity_json.IdentityCurationError
IdentityTreeError = _identity_json.IdentityTreeError


def _fail(error: IdentityCurationError | IdentityTreeError) -> None:
    """Raise ``error``; one raise site keeps fail-closed checks branch-light."""

    raise error


TRANSFORM_NAME = "curate_identity"
TRANSFORM_VERSION = "identity-provenance-v2"
ID_NAMESPACE = "spikenaut.synthetic-factory.curated-record"
_NON_NORMALIZED_PATH_MSG = (
    "source_path must already be an exact normalized POSIX relative path"
)
# Procedural routes that retain the generated bytes verbatim: their envelope is
# the measurement's attribution, so curation preserves the generated family ID
# and output bytes instead of deriving a canonical identity ID.
PRESERVED_KINDS = PRESERVED_NATIVE_KINDS


@dataclass(frozen=True)
class SourceRecord:
    """A decoded record paired with its immutable, run-relative source identity.

    ``record`` may be any strict JSON value.  Non-object values are carried to
    curation so they can be recorded as deterministic unsupported-shape
    exclusions; only supported object shapes can be retained.

    When supplied, ``source_sha256`` is the digest of the normalized UTF-8
    JSONL payload: LF is excluded together with one immediately preceding CR,
    while a CR not followed by LF remains payload.  Minimal fixtures may omit
    the digest; their mapping records that canonical JSON was hashed instead.

    ``source_json`` carries those exact JSONL bytes as decoded text when they
    are available.  It lets an identity manifest retain a source snapshot that
    can be checked against ``source_sha256`` before the transform is replayed.
    """

    record: Any
    source_path: str
    source_line: int
    source_sha256: str | None = None
    source_json: str | None = None


@dataclass(frozen=True)
class CurationResult:
    """One deterministic retain/exclude decision and its reversible mapping."""

    action: str
    record: dict[str, Any] | None
    mapping: dict[str, Any]


@dataclass(frozen=True)
class SourceIdentity:
    path: str
    line: int
    factory: str
    sha256: str
    hash_basis: str
    original: str | None


def _source_path_raw(value: object) -> str:
    if not isinstance(value, str):
        _fail(IdentityCurationError("source_path must be a non-empty relative path"))
    if not value.strip():
        _fail(IdentityCurationError("source_path must be a non-empty relative path"))
    return value


def _require_normalized_text(raw: str) -> str:
    if raw != raw.strip():
        _fail(IdentityCurationError(_NON_NORMALIZED_PATH_MSG))
    if "\\" in raw:
        _fail(IdentityCurationError(_NON_NORMALIZED_PATH_MSG))
    if "\x00" in raw:
        _fail(IdentityCurationError(_NON_NORMALIZED_PATH_MSG))
    return raw


def _require_source_path_text(value: object) -> str:
    return _require_normalized_text(_source_path_raw(value))


def _require_relative_path(raw: str) -> PurePosixPath:
    path = PurePosixPath(raw)
    if path.is_absolute():
        _fail(IdentityCurationError(
            "source_path must be normalized, relative, and contain no '.' or '..'"
        ))
    if any(part in {"", ".", ".."} for part in path.parts):
        _fail(IdentityCurationError(
            "source_path must be normalized, relative, and contain no '.' or '..'"
        ))
    if len(path.parts) < 2:
        _fail(IdentityCurationError(
            "source_path must include a factory directory and a source filename"
        ))
    return path


def normalize_source_path(value: object) -> tuple[str, str]:
    raw = _require_source_path_text(value)
    path = _require_relative_path(raw)
    normalized = path.as_posix()
    if normalized != raw:
        _fail(IdentityCurationError(
            f"source_path is not normalized: {value!r}; use {normalized!r}"
        ))
    return normalized, path.parts[0]


def _caller_supplied_digest(source, canonical_source: str, original: str | None, deps):
    digest = str(source.source_sha256).lower()
    if not deps.sha256_pattern.fullmatch(digest):
        _fail(deps.curation_error(
            "source_sha256 must be exactly 64 hexadecimal characters"
        ))
    if original is not None:
        if deps.sha256_bytes(original.encode("utf-8")) != digest:
            _fail(deps.curation_error("source_json does not match source_sha256"))
    elif deps.sha256_bytes(canonical_source.encode("utf-8")) == digest:
        # A caller-provided line digest binds the canonical source
        # representation only when the bytes actually coincide. Otherwise
        # retain the digest without claiming a hash-verified snapshot.
        original = canonical_source
    return digest, original


def _resolved_source_digest(source, canonical_source: str, original: str | None, deps):
    if source.source_sha256 is None:
        preserve_source = (
            original is not None
            and deps.classify_kind(source.record) in PRESERVED_KINDS
        )
        original = original if preserve_source else canonical_source
        digest = deps.sha256_bytes(original.encode("utf-8"))
        basis = "source-json-line-sha256" if preserve_source else "canonical-json-sha256"
        return digest, basis, original
    digest, original = _caller_supplied_digest(
        source, canonical_source, original, deps
    )
    return digest, "source-json-line-sha256", original


def _is_valid_source_line(line: object) -> bool:
    if isinstance(line, bool):
        return False
    if not isinstance(line, int):
        return False
    return line >= 1


def source_identity(source: SourceRecord, deps) -> SourceIdentity:
    if not _is_valid_source_line(source.source_line):
        _fail(deps.curation_error("source_line must be a positive integer"))
    path, factory = normalize_source_path(source.source_path)
    canonical_source = deps.canonical_json(source.record)
    original = source.source_json
    if original is not None:
        _identity_checks.validate_source_json(original, canonical_source, deps)
    digest, basis, original = _resolved_source_digest(
        source, canonical_source, original, deps
    )
    return SourceIdentity(path, source.source_line, factory, digest, basis, original)


def record_kind(record: Any) -> str:
    """Classify using the shared census-order classifier.

    Unknown shapes raise so ``curate_record`` can exclude them as
    ``identity.unsupported_record_shape``.
    """

    if not isinstance(record, Mapping):
        _fail(IdentityCurationError("record must be a JSON object"))
    kind = classify_kind(record)
    if kind == "unknown":
        _fail(IdentityCurationError(
            f"unsupported record shape (keys: {sorted(map(str, record.keys()))[:8]})"
        ))
    return kind


def declared_factory(record: Any) -> str | None:
    if not isinstance(record, Mapping):
        return None
    meta = record.get("meta")
    if not isinstance(meta, Mapping):
        return None
    value = meta.get("factory")
    if not isinstance(value, str):
        return None
    if not value.strip():
        return None
    return value


def _preference_payload_factory(
    record: Mapping[str, Any], root_factory: str | None
) -> str | None:
    side_factories = tuple(
        declared_factory(record.get(side)) for side in ("chosen", "rejected")
    )
    declared = [value for value in (root_factory, *side_factories) if value]
    if len(set(declared)) > 1:
        return None
    if root_factory is not None:
        return root_factory
    if not all(side_factories):
        return None
    if side_factories[0] != side_factories[1]:
        return None
    return side_factories[0]


def payload_factory(record: Mapping[str, Any]) -> str | None:
    """Resolve one unambiguous payload factory declaration.

    Fable preference wrappers predate a wrapper-level ``meta.factory`` and
    carry the declaration on both trajectories instead.  A top-level claim
    remains sufficient for other record kinds, but every factory claim that
    is present on a preference must agree.  Without a wrapper claim, both
    sides must independently attest the same factory.
    """

    root_factory = declared_factory(record)
    if classify_kind(record) != "preference":
        return root_factory
    return _preference_payload_factory(record, root_factory)


def canonical_id(source: SourceIdentity, kind: str, role: str) -> str:
    preimage = _identity_json.canonical_json(
        {
            "namespace": ID_NAMESPACE,
            "transform_version": TRANSFORM_VERSION,
            "source_path": source.path,
            "source_line": source.line,
            "record_kind": kind,
            "owner_role": role,
        }
    )
    digest = hashlib.sha256(preimage.encode("utf-8")).hexdigest()
    role_name = "record" if role == "/" else "trajectory"
    return f"sfcur-{kind}-{role_name}-{digest}"


def pointer(base: str, key: str) -> str:
    escaped = key.replace("~", "~0").replace("/", "~1")
    return f"/{escaped}" if base == "/" else f"{base}/{escaped}"


def _pointer_step(value: Any, raw_part: str, pointer: str) -> Any:
    part = raw_part.replace("~1", "/").replace("~0", "~")
    if not isinstance(value, Mapping):
        _fail(IdentityTreeError(f"owner_path does not exist: {pointer}"))
    if part not in value:
        _fail(IdentityTreeError(f"owner_path does not exist: {pointer}"))
    return value[part]


def pointer_value(value: Any, pointer: str) -> Any:
    if pointer == "/":
        return value
    if not isinstance(pointer, str) or not pointer.startswith("/"):
        _fail(IdentityTreeError(f"invalid owner_path: {pointer!r}"))
    current = value
    for raw_part in pointer[1:].split("/"):
        current = _pointer_step(current, raw_part, pointer)
    return current


