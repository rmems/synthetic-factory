WORKER_IO = (
    'import base64\n',
    'import builtins\n',
    'import importlib\n',
    'import json\n',
    'import logging\n',
    'import os\n',
    'import sys\n',
    'import types\n',
    'from collections import Counter, OrderedDict, defaultdict, namedtuple\n',
    'from datetime import date, datetime, time, timedelta\n',
    'from decimal import Decimal\n',
    'from fractions import Fraction\n',
    'from pathlib import Path, PurePath\n',
    '\n',
    'real_out = sys.stdout\n',
    'sys.stdout = sys.stderr\n',
    'os.chdir(sys.argv[1])\n',
    'sys.path.insert(0, str(Path(sys.argv[1]) / "src"))\n',
    'objs = {}\n',
    'ids = {}\n',
    'slots = {}\n',
    'nxt = 0\n',
    '\n',
    '\n',
    'def remember(value):\n',
    '    global nxt\n',
    '    key = id(value)\n',
    '    if key in ids:\n',
    '        return ids[key]\n',
    '    oid = nxt\n',
    '    nxt += 1\n',
    '    ids[key] = oid\n',
    '    objs[oid] = value\n',
    '    return oid\n',
    '\n',
    '\n',
    'def is_exception(value):\n',
    '    if not isinstance(value, type):\n',
    '        return False\n',
    '    try:\n',
    '        return issubclass(value, Exception)\n',
    '    except TypeError:\n',
    '        return False\n',
    '\n',
    '\n',
    'def exc_chain(value):\n',
    '    names = []\n',
    '    for base in value.__mro__[1:]:\n',
    '        if base is BaseException or base is object:\n',
    '            break\n',
    '        names.append(base.__name__)\n',
    '    return names\n',
    '\n',
    '\n',
    'def describe_exc(cls):\n',
    '    if cls.__module__ == "builtins":\n',
    '        found = getattr(builtins, cls.__name__, None)\n',
    '        if found is cls:\n',
    '            return {"builtin": cls.__name__}\n',
    '    root = str(cls.__module__).split(".", 1)[0]\n',
    '    if root in sys.stdlib_module_names:\n',
    '        return {"module": cls.__module__, "qualname": cls.__qualname__, "name": cls.__name__}\n',
    '    bases = []\n',
    '    for base in cls.__bases__:\n',
    '        if base is BaseException or base is object:\n',
    '            continue\n',
    '        bases.append(describe_exc(base))\n',
    '    return {"oid": remember(cls), "name": cls.__name__, "bases": bases}\n',
    '\n',
    '\n',
    'def dataclass_names(cls):\n',
    '    fields = getattr(cls, "__dataclass_fields__", None)\n',
    '    if not isinstance(fields, dict):\n',
    '        return None\n',
    '    names = []\n',
    '    for name, field in fields.items():\n',
    '        marker = getattr(field, "_field_type", None)\n',
    '        if getattr(marker, "name", None) != "_FIELD":\n',
    '            continue\n',
    '        names.append(str(name))\n',
    '    return names\n',
    '\n',
    '\n',
    'def describe_class(cls):\n',
    '    if cls.__module__ == "builtins":\n',
    '        found = getattr(builtins, cls.__name__, None)\n',
    '        if isinstance(found, type):\n',
    '            return {"builtin": cls.__name__}\n',
    '    bases = []\n',
    '    for base in cls.__bases__:\n',
    '        if base is object:\n',
    '            continue\n',
    '        bases.append(describe_class(base))\n',
    '    info = {"oid": remember(cls), "name": cls.__name__, "bases": bases}\n',
    '    names = dataclass_names(cls)\n',
    '    if names is not None:\n',
    '        info["dc_fields"] = names\n',
    '    return info\n',
    '\n',
    '\n',
    '_FACTORIES = {\n',
    '    "int": int, "list": list, "set": set, "dict": dict,\n',
    '    "float": float, "str": str, "tuple": tuple,\n',
    '}\n',
    '_EXC = {}\n',
    '_NT = {}\n',
    '\n',
    '\n',
    'def pairs(value):\n',
    '    return [[put(key), put(item)] for key, item in value.items()]\n',
    '\n',
    '\n',
    'def factory_name(factory):\n',
    '    if factory is None:\n',
    '        return ""\n',
    '    name = getattr(factory, "__name__", "")\n',
    '    if name in _FACTORIES:\n',
    '        return name\n',
    '    return None\n',
    '\n',
    '\n',
    'def put_scalar(value):\n',
    '    if type(value) is complex:\n',
    '        return {"kind": "complex", "real": value.real, "imag": value.imag}\n',
    '    if type(value) is range:\n',
    '        return {\n',
    '            "kind": "range",\n',
    '            "start": value.start,\n',
    '            "stop": value.stop,\n',
    '            "step": value.step,\n',
    '        }\n',
    '    if type(value) is slice:\n',
    '        return {\n',
    '            "kind": "slice",\n',
    '            "start": value.start,\n',
    '            "stop": value.stop,\n',
    '            "step": value.step,\n',
    '        }\n',
    '    if type(value) is timedelta:\n',
    '        return {\n',
    '            "kind": "timedelta",\n',
    '            "days": value.days,\n',
    '            "seconds": value.seconds,\n',
    '            "micro": value.microseconds,\n',
    '        }\n',
    '    if type(value) is time:\n',
    '        return {"kind": "time", "data": value.isoformat()}\n',
    '    if isinstance(value, PurePath):\n',
    '        return {"kind": "path", "data": str(value), "cls": type(value).__name__}\n',
    '    return None\n',
    '\n',
    '\n',
    'def put_mapping(value):\n',
    '    if isinstance(value, Counter):\n',
    '        return {"kind": "counter", "items": pairs(value)}\n',
    '    if isinstance(value, defaultdict):\n',
    '        name = factory_name(value.default_factory)\n',
    '        if name is None:\n',
    '            return None\n',
    '        return {"kind": "default", "items": pairs(value), "factory": name}\n',
    '    if isinstance(value, OrderedDict):\n',
    '        return {"kind": "ordered", "items": pairs(value)}\n',
    '    if type(value) is dict:\n',
    '        return {"kind": "dict", "items": pairs(value)}\n',
    '    return None\n',
    '\n',
    '\n',
    'def put_namedtuple(value):\n',
    '    fields = getattr(value, "_fields", None)\n',
    '    if not isinstance(value, tuple) or type(value) is tuple:\n',
    '        return None\n',
    '    if not isinstance(fields, tuple):\n',
    '        return None\n',
    '    return {\n',
    '        "kind": "namedtuple",\n',
    '        "name": type(value).__name__,\n',
    '        "fields": list(fields),\n',
    '        "items": [put(item) for item in value],\n',
    '    }\n',
    '\n',
    '\n',
    'def put(value):\n',
    '    if value is None:\n',
    '        return {"kind": "value", "value": None}\n',
    '    if isinstance(value, ParentProxy):\n',
    '        return {"kind": "cb", "cb": value._cb}\n',
    '    if value is NotImplemented:\n',
    '        return {"kind": "notimplemented"}\n',
    '    if isinstance(value, (bool, int, float, str)):\n',
    '        return {"kind": "value", "value": value}\n',
    '    if type(value) is bytes or type(value) is bytearray:\n',
    '        raw = bytes(value)\n',
    '        return {"kind": "bytes", "data": base64.b64encode(raw).decode("ascii")}\n',
    '    if isinstance(value, Decimal):\n',
    '        return {"kind": "decimal", "data": str(value)}\n',
    '    if isinstance(value, Fraction):\n',
    '        return {"kind": "fraction", "n": value.numerator, "d": value.denominator}\n',
    '    if isinstance(value, datetime):\n',
    '        return {"kind": "datetime", "data": value.isoformat()}\n',
    '    if isinstance(value, date):\n',
    '        return {"kind": "date", "data": value.isoformat()}\n',
    '    scalar = put_scalar(value)\n',
    '    if scalar is not None:\n',
    '        return scalar\n',
    '    if type(value) is list:\n',
    '        return {"kind": "list", "items": [put(item) for item in value]}\n',
    '    named = put_namedtuple(value)\n',
    '    if named is not None:\n',
    '        return named\n',
    '    if type(value) is tuple:\n',
    '        return {"kind": "tuple", "items": [put(item) for item in value]}\n',
    '    mapped = put_mapping(value)\n',
    '    if mapped is not None:\n',
    '        return mapped\n',
    '    if type(value) is set:\n',
    '        return {"kind": "set", "items": [put(item) for item in value]}\n',
    '    if type(value) is frozenset:\n',
    '        return {"kind": "frozenset", "items": [put(item) for item in value]}\n',
    '    if is_exception(value):\n',
    '        info = describe_exc(value)\n',
    '        info["kind"] = "exc_type"\n',
    '        return info\n',
    '    if isinstance(value, type):\n',
    '        info = describe_class(value)\n',
    '        info["kind"] = "class"\n',
    '        return info\n',
    '    return {"kind": "obj", "oid": remember(value), "cls": describe_class(type(value))}\n',
    '\n',
    '\n',
    'def import_stdlib(ref):\n',
    '    module = ref.get("m") if isinstance(ref, dict) else None\n',
    '    qual = ref.get("q") if isinstance(ref, dict) else None\n',
    '    root = str(module or "").split(".", 1)[0]\n',
    '    if root not in sys.stdlib_module_names or not isinstance(qual, str):\n',
    '        return ref\n',
    '    found = importlib.import_module(module)\n',
    '    for part in qual.split("."):\n',
    '        found = getattr(found, part)\n',
    '    return found\n',
    '\n',
    '\n',
    'def rebuild_reduce(value):\n',
    '    try:\n',
    '        func = import_stdlib(value.get("reduce"))\n',
    '        args = tuple(decode(item) for item in value.get("args") or ())\n',
    '        obj = func(*args)\n',
    '    except Exception:\n',
    '        return value\n',
    '    if "state" not in value:\n',
    '        return obj\n',
    '    raw = value["state"]\n',
    '    if isinstance(raw, list):\n',
    '        state = {decode(pair[0]): decode(pair[1]) for pair in raw}\n',
    '    else:\n',
    '        state = decode(raw)\n',
    '    setter = getattr(obj, "__setstate__", None)\n',
    '    if setter is not None:\n',
    '        setter(state)\n',
    '        return obj\n',
    '    if isinstance(state, dict):\n',
    '        obj.__dict__.update(state)\n',
    '    return obj\n',
    '\n',
    '\n',
    'def decode(value):\n',
    '    if not isinstance(value, dict):\n',
    '        return value\n',
    '    if "record" in value:\n',
    '        fields = {key: decode(item) for key, item in value["record"].items()}\n',
    '        return types.SimpleNamespace(**fields)\n',
    '    if "cb" in value:\n',
    '        return ParentProxy(value["cb"])\n',
    '    if "ref" in value:\n',
    '        return objs[value["ref"]]\n',
    '    if "seq" in value:\n',
    '        items = [decode(item) for item in value["seq"]]\n',
    '        if value.get("tuple"):\n',
    '            return tuple(items)\n',
    '        if value.get("slot") is not None:\n',
    '            slots[value["slot"]] = items\n',
    '        return items\n',
    '    if "map" in value:\n',
    '        decoded = {decode(pair[0]): decode(pair[1]) for pair in value["map"]}\n',
    '        if value.get("slot") is not None:\n',
    '            slots[value["slot"]] = decoded\n',
    '        return decoded\n',
    '    if "set" in value:\n',
    '        items = [decode(item) for item in value["set"]]\n',
    '        if value.get("frozen"):\n',
    '            return frozenset(items)\n',
    '        decoded = set(items)\n',
    '        if value.get("slot") is not None:\n',
    '            slots[value["slot"]] = decoded\n',
    '        return decoded\n',
    '    if "bytes" in value:\n',
    '        raw = base64.b64decode(value["bytes"])\n',
    '        if value.get("slot") is None:\n',
    '            return raw\n',
    '        buf = bytearray(raw)\n',
    '        slots[value["slot"]] = buf\n',
    '        return buf\n',
    '    if "decimal" in value:\n',
    '        return Decimal(value["decimal"])\n',
    '    if "fraction" in value:\n',
    '        return Fraction(value["fraction"], value["d"])\n',
    '    if "datetime" in value:\n',
    '        return datetime.fromisoformat(value["datetime"])\n',
    '    if "date" in value:\n',
    '        return date.fromisoformat(value["date"])\n',
    '    if "complex" in value:\n',
    '        spec = value["complex"]\n',
    '        return complex(spec[0], spec[1])\n',
    '    if "range" in value:\n',
    '        spec = value["range"]\n',
    '        return range(spec[0], spec[1], spec[2])\n',
    '    if "slice" in value:\n',
    '        spec = value["slice"]\n',
    '        return slice(spec[0], spec[1], spec[2])\n',
    '    if "timedelta" in value:\n',
    '        spec = value["timedelta"]\n',
    '        return timedelta(spec[0], spec[1], spec[2])\n',
    '    if "time" in value:\n',
    '        return time.fromisoformat(value["time"])\n',
    '    if "path" in value:\n',
    '        return rebuild_path(value.get("cls"), value["path"])\n',
    '    if "counter" in value:\n',
    '        return remember_slot(value, Counter(mapped(value["counter"])))\n',
    '    if "ordered" in value:\n',
    '        return remember_slot(value, OrderedDict(mapped(value["ordered"])))\n',
    '    if "default" in value:\n',
    '        factory = _FACTORIES.get(value.get("factory") or "")\n',
    '        return remember_slot(value, defaultdict(factory, mapped(value["default"])))\n',
    '    if "namedtuple" in value:\n',
    '        return rebuild_namedtuple(value)\n',
    '    if "reduce" in value:\n',
    '        return rebuild_reduce(value)\n',
    '    if "cls" in value:\n',
    '        return import_stdlib(value["cls"])\n',
    '    return value\n',
    '\n',
)
WORKER_IO = ''.join(WORKER_IO)

if __package__:  # pragma: no cover - package-child import path
    _expose_package_sibling(__name__)
