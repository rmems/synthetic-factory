def count_jsonl_lines(path: Path) -> int:
    n = 0
    with path.open("rb") as fh:
        for line in fh:
            if line.strip():
                n += 1
    return n


def link_or_copy(src: Path, dst: Path, expected_sha256: str | None = None) -> None:
    """Atomically replace any prior snapshot with an independent copy.

    Hub working trees are mutable. A hard link would let a later edit under
    ``HF_ROOT`` silently mutate the immutable raw factory source, while
    retaining a symlink could publish stale or unrelated bytes. Replacing the
    destination from a temporary regular file handles both cases safely.
    """
    dst.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        dir=dst.parent, prefix=f".{dst.name}.", suffix=".tmp", delete=False
    ) as handle:
        temporary = Path(handle.name)
    try:
        flags = os.O_RDONLY
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        try:
            source_fd = os.open(src, flags)
        except OSError as exc:
            raise SystemExit(f"unsafe snapshot source file: {src}: {exc}") from exc
        try:
            if not stat.S_ISREG(os.fstat(source_fd).st_mode):
                raise SystemExit(f"unsafe snapshot source file: {src}")
            with os.fdopen(source_fd, "rb") as source_handle, temporary.open(
                "wb"
            ) as temporary_handle:
                source_fd = -1
                shutil.copyfileobj(source_handle, temporary_handle)
                temporary_handle.flush()
                os.fsync(temporary_handle.fileno())
        finally:
            if source_fd >= 0:
                os.close(source_fd)
        if expected_sha256 is not None and file_sha256(temporary) != expected_sha256:
            raise SystemExit(f"snapshot source changed after manifest validation: {src}")
        temporary.replace(dst)
    finally:
        temporary.unlink(missing_ok=True)


def replace_snapshot_text(dst: Path, content: str) -> None:
    """Atomically replace a managed text file without following a symlink."""
    if not dst.parent.is_dir() or dst.parent.is_symlink():
        raise SystemExit(f"unsafe snapshot parent directory: {dst.parent}")
    if (dst.exists() or dst.is_symlink()) and dst.is_dir():
        raise SystemExit(f"unsafe snapshot metadata endpoint: {dst}")
    with tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        dir=dst.parent,
        prefix=f".{dst.name}.",
        suffix=".tmp",
        delete=False,
    ) as handle:
        temporary = Path(handle.name)
        handle.write(content)
    try:
        temporary.replace(dst)
    finally:
        temporary.unlink(missing_ok=True)


def snapshot_directories(dest: Path) -> tuple[Path, Path]:
    """Create a real, contained raw/metadata tree for one Hub snapshot."""
    if HF_ROOT.exists() or HF_ROOT.is_symlink():
        if not HF_ROOT.is_dir() or HF_ROOT.is_symlink():
            raise SystemExit(f"unsafe snapshot directory: {HF_ROOT}")
    else:
        HF_ROOT.mkdir(parents=True)
    root = HF_ROOT.resolve()

    if dest.parent != HF_ROOT:
        raise SystemExit(f"snapshot destination escaped Hub root: {dest}")
    for directory in (dest, dest / "data", dest / "data" / "raw", dest / "data" / "metadata"):
        if directory.exists() or directory.is_symlink():
            if not directory.is_dir() or directory.is_symlink():
                raise SystemExit(f"unsafe snapshot directory: {directory}")
        else:
            directory.mkdir()
        try:
            directory.resolve().relative_to(root)
        except ValueError as exc:
            raise SystemExit(f"snapshot directory escaped Hub root: {directory}") from exc
    return dest / "data" / "raw", dest / "data" / "metadata"


def batch_label(path: Path) -> tuple[int, str, str] | None:
    """Return a sortable, zero-padded round label for a published batch."""
    match = BATCH_NAME_RE.fullmatch(path.name)
    if match is None:
        return None
    number = int(match.group(1))
    suffix = match.group(2)
    return number, suffix, f"r{number:02d}{suffix}"


def is_snapshot_payload(path: Path) -> bool:
    """Whether a raw file has a name owned by the public snapshot mirror."""
    return batch_label(path) is not None or path.name in LEGACY_R1_NAMES


def is_regular_source_file(path: Path) -> bool:
    """Whether a source file can be safely copied into a public snapshot."""
    return path.is_file() and not path.is_symlink()


def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def completed_manifests(src: Path) -> dict[int, dict]:
    """Load and validate every transactional completion marker in a factory."""
    manifests = {}
    for marker in sorted(src.glob("ROUND-r*.complete.json")):
        match = COMPLETE_MARKER_RE.fullmatch(marker.name)
        if match is None:
            continue
        if not is_regular_source_file(marker):
            raise SystemExit(f"unsafe completion marker: {marker}")
        round_number = int(match.group(1))
        try:
            manifest = json.loads(marker.read_text())
        except (OSError, UnicodeError, json.JSONDecodeError) as exc:
            raise SystemExit(f"cannot read completion marker {marker}: {exc}") from exc
        if not isinstance(manifest, dict):
            raise SystemExit(f"completion marker must be an object: {marker}")
        if manifest.get("factory") != src.name or manifest.get("round") != round_number:
            raise SystemExit(f"completion marker identity mismatch: {marker}")
        if manifest.get("commit_point") != marker.name:
            raise SystemExit(f"completion marker commit point mismatch: {marker}")
        if not isinstance(manifest.get("files"), list):
            raise SystemExit(f"completion marker files must be an array: {marker}")
        for entry in manifest["files"]:
            name = entry.get("name") if isinstance(entry, dict) else None
            if not isinstance(name, str) or not name or Path(name).name != name:
                raise SystemExit(f"completion marker has an unsafe file entry: {marker}")
            if name in (f"batch-r{round_number:02d}.jsonl", f"NOTES-r{round_number:02d}.md"):
                continue
            artifact = src / name
            if not is_regular_source_file(artifact):
                raise SystemExit(f"completion marker has no regular artifact: {artifact}")
            file_matches_manifest(artifact, manifest)
        batch = src / f"batch-r{round_number:02d}.jsonl"
        if not is_regular_source_file(batch):
            raise SystemExit(f"completion marker has no regular batch: {marker}")
        file_matches_manifest(batch, manifest)
        notes = src / f"NOTES-r{round_number:02d}.md"
        if not is_regular_source_file(notes):
            raise SystemExit(f"completion marker has no regular notes: {marker}")
        file_matches_manifest(notes, manifest)
        manifests[round_number] = manifest
    return manifests


