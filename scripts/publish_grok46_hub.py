def hub_name(slug: str) -> str:
    if slug == "safety-calibration-factory":
        return "safety-calibration-cases"
    if slug == "sparse-reward-long-task-factory":
        return "sparse-reward-long-tasks"
    if slug == "multi-agent-coordination-factory":
        return "multi-agent-coordination-transcripts"
    if slug.endswith("-preference-factory"):
        return slug[: -len("-factory")] + "-pairs"
    if slug.endswith("-trajectory-factory"):
        return slug.replace("-trajectory-factory", "-trajectories")
    if slug.endswith("-factory"):
        return slug[: -len("-factory")] + "-trajectories"
    raise ValueError(slug)


def pretty_name(hub: str) -> str:
    return hub.replace("-", " ").title()


def factories() -> list[dict]:
    slugs = sorted(p.name for p in FACTORY_ROOT.iterdir() if p.is_dir())
    out = []
    for slug in slugs:
        if slug not in META:
            raise SystemExit(f"missing META for {slug}")
        blurb, extra = META[slug]
        hub = hub_name(slug)
        tags = ["synthetic-data", "agentic-workflows", "grok-4.6", "provenance"]
        if "pairs" in hub:
            tags.append("preference-data")
        else:
            tags.append("trajectories")
        tags.extend(extra)
        # de-dupe preserve order
        seen = set()
        clean = []
        for t in tags:
            if t in seen:
                continue
            low = t.lower()
            if any(b in low for b in BANNED_TAG_SUBSTR):
                raise SystemExit(f"banned tag {t} on {slug}")
            seen.add(t)
            clean.append(t)
        out.append({"slug": slug, "hub": hub, "pretty": pretty_name(hub), "blurb": blurb, "tags": clean})
    return out


def run(cmd: list[str], check: bool = True) -> subprocess.CompletedProcess:
    print("+", " ".join(cmd), flush=True)
    return subprocess.run(cmd, check=check, text=True)


def count_jsonl_lines(path: Path) -> int:
    n = 0
    with path.open("rb") as fh:
        for line in fh:
            if line.strip():
                n += 1
    return n


def link_or_copy(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists() or dst.is_symlink():
        if dst.is_symlink() or dst.stat().st_ino == src.stat().st_ino:
            return
        dst.unlink()
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def snapshot_one(item: dict) -> dict:
    src = FACTORY_ROOT / item["slug"]
    dest = HF_ROOT / item["hub"]
    raw = dest / "data" / "raw"
    meta = dest / "data" / "metadata"
    raw.mkdir(parents=True, exist_ok=True)
    meta.mkdir(parents=True, exist_ok=True)
    batches = sorted(src.glob("batch-r*.jsonl"))
    notes = sorted(src.glob("NOTES-r*.md"))
    records = 0
    bytes_ = 0
    last = 0
    for b in batches:
        link_or_copy(b, raw / b.name)
        records += count_jsonl_lines(b)
        bytes_ += b.stat().st_size
        try:
            last = max(last, int(b.stem.split("-r", 1)[1].rstrip("c") or "0"))
        except ValueError:
            pass
    for n in notes:
        link_or_copy(n, meta / n.name)
    first = "r01"
    last_s = f"r{last}" if last else "r01"
    card = render_card(item, records=records, bytes_=bytes_, first=first, last=last_s)
    (dest / "README.md").write_text(card, encoding="utf-8")
    if not LICENSE_SRC.exists():
        raise SystemExit(f"missing LICENSE at {LICENSE_SRC}")
    license_dst = dest / "LICENSE"
    if LICENSE_SRC.resolve() != license_dst.resolve():
        shutil.copy2(LICENSE_SRC, license_dst)
    (dest / "ATTRIBUTION.md").write_text(
        "Generated by Grok 4.6 via the Synthetic Data Factory agentic lane.\n"
        "Public raw snapshot; not training-ready.\n\n"
        f"{COAUTHOR}\n",
        encoding="utf-8",
    )
    # YAML tags only — body may say "not labeled as Spikenaut".
    fm = card.split("---", 2)
    tag_block = fm[1] if len(fm) >= 3 else ""
    for line in tag_block.splitlines():
        low = line.strip().lstrip("- ").lower()
        if any(b == low or low.startswith(b + "-") for b in BANNED_TAG_SUBSTR):
            raise SystemExit(f"banned YAML tag {low!r} on {item['hub']}")
    return {
        "hub": item["hub"],
        "slug": item["slug"],
        "records": records,
        "batches": len(batches),
        "notes": len(notes),
        "bytes": bytes_,
        "last": last,
    }


