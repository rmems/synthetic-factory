def legacy_snapshot_paths(src: Path, baseline: int) -> list[Path]:
    """Return legacy-baseline payload and matching note paths for byte pinning."""
    paths = transaction_legacy_baseline_jsonl_paths(src, baseline)
    labels = {
        label[2]
        for path in paths
        if (label := batch_label(path)) is not None
    }
    labels.update(
        f"r{label[0]:02d}"
        for path in paths
        if (label := batch_label(path)) is not None
    )
    if any(path.name in LEGACY_R1_NAMES for path in paths):
        labels.add("r01")
    paths.extend(
        path
        for path in sorted(src.glob("NOTES-r*.md"))
        if is_regular_source_file(path)
        and (match := NOTES_NAME_RE.fullmatch(path.name)) is not None
        and f"r{int(match.group(1)):02d}{match.group(2)}" in labels
    )
    return paths


def marker_mode_state(
    src: Path,
) -> tuple[int | None, dict[int, dict], dict[str, str]]:
    """Return a factory's baseline, manifests, and pinned legacy digests once."""
    mode_path = src / ".round-marker-mode.json"
    if not mode_path.exists() and not mode_path.is_symlink():
        return None, {}, {}
    if not is_regular_source_file(mode_path):
        raise SystemExit(f"unsafe marker mode file: {mode_path}")
    try:
        mode = json.loads(mode_path.read_text())
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise SystemExit(f"cannot read marker mode for {src}: {exc}") from exc
    if not isinstance(mode, dict) or mode.get("version") != 1:
        raise SystemExit(f"unsupported marker mode version in {mode_path}")
    if mode.get("commit_point") != "ROUND-rNN.complete.json":
        raise SystemExit(f"invalid marker mode commit point in {mode_path}")
    baseline = mode.get("legacy_baseline")
    if not isinstance(baseline, int) or isinstance(baseline, bool) or baseline < 0:
        raise SystemExit(f"invalid legacy_baseline in {mode_path}")
    manifests = completed_manifests(src)
    legacy_frontier, legacy_named_baseline = discovered_legacy_frontier(src)
    if baseline > legacy_frontier:
        raise SystemExit(
            f"legacy_baseline in {mode_path} exceeds discovered legacy frontier "
            f"r{legacy_frontier:02d}"
        )
    if baseline < legacy_named_baseline:
        raise SystemExit(f"legacy_baseline in {mode_path} excludes legacy r01 payloads")
    legacy_paths = legacy_snapshot_paths(src, baseline)
    legacy_sha256 = {path.name: file_sha256(path) for path in legacy_paths}
    validate_legacy_baseline_payloads(src, baseline)
    validated_legacy_sha256 = {
        path.name: file_sha256(path)
        for path in legacy_snapshot_paths(src, baseline)
    }
    if legacy_sha256 != validated_legacy_sha256:
        raise SystemExit(f"legacy baseline changed during validation: {src}")
    try:
        manifests = transaction_completed_manifests(src)
    except TransactionError as exc:
        raise SystemExit(str(exc)) from exc
    return baseline, manifests, validated_legacy_sha256


def file_matches_manifest(path: Path, manifest: dict) -> bool:
    """Verify a completed source file against its transaction manifest entry."""
    entries = [
        entry
        for entry in manifest["files"]
        if isinstance(entry, dict) and entry.get("name") == path.name
    ]
    if len(entries) != 1:
        raise SystemExit(f"completion marker has no unique file entry for {path}")
    expected = entries[0].get("sha256")
    if not isinstance(expected, str) or SHA256_RE.fullmatch(expected) is None:
        raise SystemExit(f"completion marker has invalid file hash for {path}")
    if file_sha256(path) != expected:
        raise SystemExit(f"completed file hash mismatch: {path}")
    return True


def manifest_file_sha256(path: Path, manifest: dict) -> str:
    """Return the unique validated manifest digest for one committed file name."""
    entries = [
        entry
        for entry in manifest["files"]
        if isinstance(entry, dict) and entry.get("name") == path.name
    ]
    if len(entries) != 1:
        raise SystemExit(f"completion marker has no unique file entry for {path}")
    digest = entries[0].get("sha256")
    if not isinstance(digest, str) or SHA256_RE.fullmatch(digest) is None:
        raise SystemExit(f"completion marker has invalid file hash for {path}")
    return digest


def snapshot_manifest_sha256(
    path: Path,
    marker_state: tuple[int | None, dict[int, dict], dict[str, str]],
) -> str | None:
    """Return the committed digest that must still match during snapshot copy."""
    baseline, manifests, legacy_sha256 = marker_state
    if baseline is None:
        return None
    if path.name in legacy_sha256:
        return legacy_sha256[path.name]
    label = batch_label(path)
    if label is not None:
        round_number, suffix, _round_label = label
    else:
        match = NOTES_NAME_RE.fullmatch(path.name)
        if match is None:
            return None
        round_number = int(match.group(1))
        suffix = match.group(2)
    if round_number <= baseline or suffix or round_number not in manifests:
        return None
    return manifest_file_sha256(path, manifests[round_number])


def published_batches(
    src: Path,
    marker_state: tuple[int | None, dict[int, dict], dict[str, str]] | None = None,
) -> list[Path]:
    """Return marker-visible raw payloads from a factory.

    Marker-mode baselines can originate in one of the pre-transaction JSONL
    filenames.  Those files are transaction-visible at r01, so a public
    snapshot must retain them alongside the newer ``batch-rNN.jsonl`` form.
    """
    batches = [
        path
        for path in src.glob("batch-r*.jsonl")
        if is_regular_source_file(path) and batch_label(path) is not None
    ]
    if marker_state is None:
        marker_state = marker_mode_state(src)
    baseline, manifests, _legacy_sha256 = marker_state
    if baseline is None:
        legacy_batches = [
            path
            for path in src.glob("*.jsonl")
            if path.name in LEGACY_R1_NAMES and is_regular_source_file(path)
        ]
        return sorted([*batches, *legacy_batches])
    visible_batches = [
        path
        for path in batches
        if (label := batch_label(path)) is not None
        and (
            label[0] <= baseline
            or (
                not label[1]
                and label[0] in manifests
                and file_matches_manifest(path, manifests[label[0]])
            )
        )
    ]
    legacy_baseline = [
        path
        for path in src.glob("*.jsonl")
        if baseline >= 1 and path.name in LEGACY_R1_NAMES and is_regular_source_file(path)
    ]
    return sorted([*visible_batches, *legacy_baseline])


def published_notes(
    src: Path,
    batches: list[Path],
    marker_state: tuple[int | None, dict[int, dict], dict[str, str]] | None = None,
) -> list[Path]:
    """Return notes that correspond to exactly one visible published batch."""
    labels = {label[2] for batch in batches if (label := batch_label(batch)) is not None}
    if any(batch.name in LEGACY_R1_NAMES for batch in batches):
        labels.add("r01")
    if marker_state is None:
        marker_state = marker_mode_state(src)
    baseline, manifests, _legacy_sha256 = marker_state
    if baseline is not None:
        labels.update(
            f"r{label[0]:02d}"
            for batch in batches
            if (label := batch_label(batch)) is not None
            and label[0] <= baseline
        )

    def visible_note(path: Path) -> bool:
        match = NOTES_NAME_RE.fullmatch(path.name)
        if match is None or not is_regular_source_file(path):
            return False
        round_number = int(match.group(1))
        suffix = match.group(2)
        label = f"r{round_number:02d}{suffix}"
        if label not in labels:
            return False
        if baseline is None or round_number <= baseline:
            return True
        return not suffix and round_number in manifests and file_matches_manifest(
            path, manifests[round_number]
        )

    return sorted(
        path
        for path in src.glob("NOTES-r*.md")
        if visible_note(path)
    )


def reconcile_snapshot_entries(
    directory: Path, desired_names: set[str], description: str
) -> None:
    """Remove unmanaged files while refusing unexpected directory trees."""
    for existing in directory.iterdir():
        if existing.name in desired_names:
            continue
        if existing.is_file() or existing.is_symlink():
            existing.unlink()
        else:
            raise SystemExit(f"unsafe non-file {description}: {existing}")


def snapshot_one(item: dict) -> dict:
    src = factory_source(item["slug"])
    dest = HF_ROOT / item["hub"]
    if not LICENSE_SRC.is_file():
        raise SystemExit(f"missing repository LICENSE at {LICENSE_SRC}")
    raw, meta = snapshot_directories(dest)
    marker_state = marker_mode_state(src)
    batches = published_batches(src, marker_state)
    notes = published_notes(src, batches, marker_state)
    records = 0
    bytes_ = 0
    labels = []
    desired_batch_names = {batch.name for batch in batches}
    desired_note_names = {note.name for note in notes}
    reconcile_snapshot_entries(
        dest,
        {"data", "README.md", "LICENSE", "ATTRIBUTION.md"},
        "snapshot root entry",
    )
    reconcile_snapshot_entries(
        dest / "data", {"raw", "metadata"}, "snapshot data entry"
    )
    reconcile_snapshot_entries(raw, desired_batch_names, "snapshot payload")
    reconcile_snapshot_entries(meta, desired_note_names, "snapshot metadata")
    for b in batches:
        copied = raw / b.name
        link_or_copy(b, copied, snapshot_manifest_sha256(b, marker_state))
        records += count_jsonl_lines(copied)
        bytes_ += copied.stat().st_size
        labels.append(batch_label(b))
    for n in notes:
        link_or_copy(n, meta / n.name, snapshot_manifest_sha256(n, marker_state))
    labels = [
        (batch, label)
        for batch, label in zip(batches, labels)
        if label is not None
    ]
    batch_only = len(labels) == len(batches) and all(
        batch.name == f"batch-{label[2]}.jsonl" for batch, label in labels
    )
    first = min(label for _batch, label in labels)[2] if labels and batch_only else None
    last_s = max(label for _batch, label in labels)[2] if labels and batch_only else None
    card = render_card(
        item,
        records=records,
        bytes_=bytes_,
        first=first,
        last=last_s,
        payload_names=[batch.name for batch in batches],
    )
    replace_snapshot_text(dest / "README.md", card)
    license_dst = dest / "LICENSE"
    link_or_copy(LICENSE_SRC, license_dst)
    replace_snapshot_text(
        dest / "ATTRIBUTION.md",
        ATTRIBUTION,
    )
    # YAML tags only — body may say "not labeled as Spikenaut".
    fm = card.split("---", 2)
    tag_block = fm[1] if len(fm) >= 3 else ""
    for line in tag_block.splitlines():
        low = line.strip().lstrip("- ").lower()
        if any(b == low or low.startswith(b + "-") for b in BANNED_TAG_SUBSTR):
            raise SystemExit(f"banned YAML tag {low!r} on {item['hub']}")
    return {
        "hub": item["hub"],
        "slug": item["slug"],
        "records": records,
        "batches": len(batches),
        "notes": len(notes),
        "bytes": bytes_,
        "last": last_s,
    }


def render_card(
    item: dict,
    *,
    records: int,
    bytes_: int,
    first: str | None,
    last: str | None,
    payload_names: list[str] | None = None,
) -> str:
    tags = "\n".join(f"- {t}" for t in item["tags"])
    kb = max(1, bytes_ // 1024)
    if first is None or last is None:
        if payload_names:
            names = ", ".join(f"`data/raw/{name}`" for name in payload_names)
            payload = (
                f"The release contains {records} raw records across {len(payload_names)} "
                f"published JSONL payload(s) ({names}; ~{kb} KB), snapshotted from"
            )
        else:
            payload = (
                "This snapshot currently contains no published raw batch files. "
                "It does not claim a `data/raw/batch-rNN.jsonl` payload. The factory "
                "source tree is"
            )
    else:
        payload = (
            f"The release contains {records} raw records across\n"
            f"`data/raw/batch-{first}.jsonl` through `data/raw/batch-{last}.jsonl` "
            f"(~{kb} KB), snapshotted from"
        )
    return f"""---
pretty_name: {item['pretty']}
license: apache-2.0
language:
- en
tags:
{tags}
---

# {item['pretty']}

> **Release status:** The raw, uncurated payload is now published under
> `data/raw/`. It is available for inspection and reproducibility, but it is
> **not training-ready**.

> **Visibility:** public raw-data repository.

{item['blurb']}

## Intended model target

This is a general agentic research dataset in the Grok 4.6 agentic factory.
It is independent of the Fable 5 collection and is not labeled as
Spikenaut training data.

## Generation attribution

The underlying synthetic data is generated by **Grok 4.6** through the
Synthetic Data Factory agentic lane. Factory slug:
`{item['slug']}`. Source tree:
`outputs/raw/2026-08-19-agentic/{item['slug']}/`.

## Published raw payload

{payload}
`outputs/raw/2026-08-19-agentic/{item['slug']}/`. Supporting notes are under
`data/metadata/NOTES-*.md`. The factory source remains the write destination; this Hub
copy is a public evidence snapshot, not the curated training export. Public
visibility is not a training-readiness claim.

## Planned curated release

Curated training publication remains blocked until a later audit and export
pass. Do not treat this repository as a training corpus.

## Links

- [Synthetic data factory: Grok 4.6]({COLLECTION_URL})
- [Synthetic Data Factory](https://github.com/rmems/synthetic-factory)

## License

This public raw release is licensed under the [Apache License 2.0](LICENSE).
That license grants reuse permissions; it does not make the records
training-ready or factual real-world measurements.
"""


def cmd_snapshot(only: str | None = None) -> list[dict]:
    items = factories()
    stats = []
    for item in items:
        if only and item["hub"] != only and item["slug"] != only:
            continue
        stats.append(snapshot_one(item))
        print(f"snapshot {item['hub']} batches={stats[-1]['batches']} records={stats[-1]['records']}", flush=True)
    selected = {stat["hub"]: stat for stat in stats}
    inventory_stats = [
        selected[item["hub"]]
        if item["hub"] in selected
        else local_snapshot_stats(item)
        for item in items
    ]
    inv = HF_ROOT / "SYNTHETIC-DATA-FACTORY-GROK46.md"
    lines = [
        "# Synthetic data factory: Grok 4.6",
        "",
        f"Collection: {COLLECTION_URL}",
        "",
        "| Local dir | Hub dataset | Factory slug | batches | records |",
        "|---|---|---|---:|---:|",
    ]
    for s in inventory_stats:
        lines.append(
            f"| `{s['hub']}/` | [rmems/{s['hub']}](https://huggingface.co/datasets/rmems/{s['hub']}) "
            f"| `{s['slug']}` | {s['batches']} | {s['records']} |"
        )
    lines.append("")
    replace_snapshot_text(inv, "\n".join(lines))
    return stats


def local_snapshot_stats(item: dict) -> dict:
    """Summarize an existing local Hub mirror for the shared inventory."""
    raw = HF_ROOT / item["hub"] / "data" / "raw"
    batches = []
    if raw.is_dir():
        batches = sorted(
            path
            for path in raw.iterdir()
            if is_regular_source_file(path) and is_snapshot_payload(path)
        )
    labels = [label for path in batches if (label := batch_label(path)) is not None]
    return {
        "hub": item["hub"],
        "slug": item["slug"],
        "records": sum(count_jsonl_lines(path) for path in batches),
        "batches": len(batches),
        "notes": 0,
        "bytes": sum(path.stat().st_size for path in batches),
        "last": max(labels, default=(0, "", None))[2],
    }


def is_selected(item: dict, only: str | None) -> bool:
    return not only or item["hub"] == only or item["slug"] == only


def cmd_create(only: str | None = None) -> None:
    for item in factories():
        if not is_selected(item, only):
            continue
        run(
            [
                "hf",
                "repos",
                "create",
                f"rmems/{item['hub']}",
                "--type",
                "dataset",
                "--public",
                "--exist-ok",
            ]
        )


def safe_upload_directory(item: dict) -> Path:
    """Return a real Hub mirror contained beneath a real ``HF_ROOT``."""
    if not HF_ROOT.is_dir() or HF_ROOT.is_symlink():
        raise SystemExit(f"unsafe upload root: {HF_ROOT}")
    root = HF_ROOT.resolve()
    dest = HF_ROOT / item["hub"]
    if dest.parent != HF_ROOT or not dest.is_dir() or dest.is_symlink():
        raise SystemExit(f"unsafe upload directory: {dest}")
    try:
        dest.resolve().relative_to(root)
    except ValueError as exc:
        raise SystemExit(f"upload directory escaped Hub root: {dest}") from exc
    expected_directories = {Path("data"), Path("data/raw"), Path("data/metadata")}
    expected_top_files = {Path("README.md"), Path("LICENSE"), Path("ATTRIBUTION.md")}
    for path in dest.rglob("*"):
        relative = path.relative_to(dest)
        if relative in expected_directories:
            if not path.is_dir() or path.is_symlink():
                raise SystemExit(f"unsafe upload tree entry: {path}")
            continue
        if relative in expected_top_files:
            if not is_regular_source_file(path):
                raise SystemExit(f"unsafe upload tree entry: {path}")
            continue
        if (
            len(relative.parts) == 3
            and relative.parts[:2] == ("data", "raw")
            and is_regular_source_file(path)
            and is_snapshot_payload(path)
        ):
            continue
        if (
            len(relative.parts) == 3
            and relative.parts[:2] == ("data", "metadata")
            and is_regular_source_file(path)
            and NOTES_NAME_RE.fullmatch(path.name) is not None
        ):
            continue
        raise SystemExit(f"unmanaged upload tree entry: {path}")
    return dest


def validate_upload_snapshot(item: dict, dest: Path) -> None:
    """Require the complete mirror to match the current validated source."""
    src = factory_source(item["slug"])
    marker_state = marker_mode_state(src)
    batches = published_batches(src, marker_state)
    notes = published_notes(src, batches, marker_state)
    raw = dest / "data" / "raw"
    meta = dest / "data" / "metadata"
    for directory in (raw, meta):
        if not directory.is_dir() or directory.is_symlink():
            raise SystemExit(f"incomplete upload snapshot directory: {directory}")

    expected_batches = {path.name: path for path in batches}
    expected_notes = {path.name: path for path in notes}
    actual_batches = {path.name for path in raw.iterdir()}
    actual_notes = {path.name for path in meta.iterdir()}
    if actual_batches != set(expected_batches):
        raise SystemExit(f"upload snapshot payload set mismatch: {raw}")
    if actual_notes != set(expected_notes):
        raise SystemExit(f"upload snapshot metadata set mismatch: {meta}")

    for directory, expected in ((raw, expected_batches), (meta, expected_notes)):
        for name, source in expected.items():
            expected_sha256 = snapshot_manifest_sha256(source, marker_state)
            if expected_sha256 is None:
                expected_sha256 = file_sha256(source)
            if file_sha256(directory / name) != expected_sha256:
                raise SystemExit(f"upload snapshot digest mismatch: {directory / name}")

    required_top = {
        "README.md": None,
        "LICENSE": LICENSE_SRC,
        "ATTRIBUTION.md": None,
    }
    for name in required_top:
        path = dest / name
        if not is_regular_source_file(path):
            raise SystemExit(f"incomplete upload snapshot file: {path}")
    if file_sha256(dest / "LICENSE") != file_sha256(LICENSE_SRC):
        raise SystemExit(f"upload snapshot digest mismatch: {dest / 'LICENSE'}")
    try:
        attribution = (dest / "ATTRIBUTION.md").read_text()
    except (OSError, UnicodeError) as exc:
        raise SystemExit(f"cannot read upload snapshot attribution: {exc}") from exc
    if attribution != ATTRIBUTION:
        raise SystemExit(f"upload snapshot digest mismatch: {dest / 'ATTRIBUTION.md'}")

    records = sum(count_jsonl_lines(raw / batch.name) for batch in batches)
    bytes_ = sum((raw / batch.name).stat().st_size for batch in batches)
    labels = [
        (batch, label)
        for batch in batches
        if (label := batch_label(batch)) is not None
    ]
    batch_only = len(labels) == len(batches) and all(
        batch.name == f"batch-{label[2]}.jsonl" for batch, label in labels
    )
    first = min(label for _batch, label in labels)[2] if labels and batch_only else None
    last = max(label for _batch, label in labels)[2] if labels and batch_only else None
    expected_card = render_card(
        item,
        records=records,
        bytes_=bytes_,
        first=first,
        last=last,
        payload_names=[batch.name for batch in batches],
    )
    try:
        card = (dest / "README.md").read_text()
    except (OSError, UnicodeError) as exc:
        raise SystemExit(f"cannot read upload snapshot card: {exc}") from exc
    if card != expected_card:
        raise SystemExit(f"upload snapshot digest mismatch: {dest / 'README.md'}")


def cmd_upload(only: str | None = None) -> None:
    for item in factories():
        if not is_selected(item, only):
            continue
        dest = safe_upload_directory(item)
        validate_upload_snapshot(item, dest)
        run(
            [
                "hf",
                "upload",
                f"rmems/{item['hub']}",
                str(dest),
                "--type",
                "dataset",
                "--delete",
                "data/raw/*",
                "--delete",
                "data/metadata/NOTES-r*.md",
                "--commit-message",
                f"Snapshot published raw from {item['slug']}",
                "--commit-description",
                COMMIT_DESC,
            ]
        )


def cmd_collect(only: str | None = None) -> None:
    for item in factories():
        if not is_selected(item, only):
            continue
        run(
            [
                "hf",
                "collections",
                "add-item",
                COLLECTION,
                f"rmems/{item['hub']}",
                "dataset",
                "--note",
                f"Grok 4.6 {item['pretty']}. Public raw; not training-ready.",
                "--exists-ok",
            ]
        )


def cmd_status() -> None:
    print(f"{'hub':48} {'local_raw':>9} {'factory':>9}")
    for item in factories():
        local_raw = HF_ROOT / item["hub"] / "data" / "raw"
        local = (
            sum(1 for path in local_raw.iterdir() if is_snapshot_payload(path))
            if local_raw.is_dir()
            else 0
        )
        factory_dir = FACTORY_ROOT / item["slug"]
        factory = 0
        if factory_dir.is_dir():
            marker_state = marker_mode_state(factory_dir)
            if marker_state[0] is None:
                factory = sum(
                    1 for path in factory_dir.iterdir() if is_snapshot_payload(path)
                )
            else:
                factory = len(published_batches(factory_dir, marker_state))
        print(f"{item['hub']:48} {local:9d} {factory:9d}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["snapshot", "create", "upload", "collect", "status", "all"])
    ap.add_argument("--only")
    args = ap.parse_args()
    if args.only and not any(is_selected(item, args.only) for item in factories()):
        print(f"unknown --only target: {args.only}", file=sys.stderr)
        return 2
    who = subprocess.run(["hf", "auth", "whoami", "--format", "json"], capture_output=True, text=True)
    if who.returncode != 0:
        print(who.stderr, file=sys.stderr)
        return 2
    ident = json.loads(who.stdout)
    if ident.get("user") != "rmems":
        print(f"refusing: whoami={ident!r}", file=sys.stderr)
        return 2
    if args.cmd == "snapshot":
        cmd_snapshot(args.only)
    elif args.cmd == "create":
        cmd_create(args.only)
    elif args.cmd == "upload":
        cmd_upload(args.only)
    elif args.cmd == "collect":
        cmd_collect(args.only)
    elif args.cmd == "status":
        cmd_status()
    elif args.cmd == "all":
        cmd_snapshot(args.only)
        cmd_create(args.only)
        cmd_upload(args.only)
        cmd_collect(args.only)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
