_LETTERS = "abcdefghijklmnopqrstuvwxyz"


def _suf(i: int) -> str:
    return f"s{i:03d}{_LETTERS[i % 26]}"


def eval_pair(
    ok_slug,
    ok_dom,
    bad_slug,
    bad_dom,
    planted_ok,
    planted_bad,
    leftover_ok,
    leftover_bad,
    first_ok,
    first_bad,
    fix_ok,
    fix_bad,
    i,
    kind,
):
    s0, s1 = _suf(i * 2), _suf(i * 2 + 1)
    ok_src = f"evals/{ok_dom.replace('-', '_')}.py"
    bad_src = f"evals/{bad_dom.replace('-', '_')}.py"
    ok_test = f"tests/test_{ok_dom.replace('-', '_')}_sha.py"
    bad_test = f"tests/test_{bad_dom.replace('-', '_')}_sha.py"
