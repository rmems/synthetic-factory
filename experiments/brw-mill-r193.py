def clip(text: str, n: int = 240) -> str:
    text = " ".join(text.split())
    if len(text) <= n:
        return text
    return text[: n - 1].rstrip() + "…"


def st(n: int, basis: str, name: str, args: dict, obs: str, reflection: str | None = None) -> dict:
    basis = clip(basis)
    prefix = basis.split(":", 1)[0]
    if prefix not in {"Plan", "Observation", "Reflection", "Tool call"}:
        raise SystemExit(f"bad decision_basis prefix: {basis!r}")
    if len(basis) > 240:
        raise SystemExit(f"decision_basis too long ({len(basis)}): {basis}")
    step = {
        "n": n,
        "decision_basis": basis,
        "tool_call": {"name": name, "args": args},
        "observation": obs,
    }
    if reflection:
        step["reflection"] = reflection
    return step


def rec(eid: str, goal: str, plan: str, steps: list, outcome: str, reward: dict, meta: dict) -> dict:
    if not 13 <= len(steps) <= 16:
        raise SystemExit(f"{eid}: need 13–16 steps, got {len(steps)}")
    for i, step in enumerate(steps, 1):
        if step["n"] != i:
            raise SystemExit(f"{eid}: step n gap at {i}")
        blob = json.dumps(step)
        for key in ("thought", "chain_of_thought", "scratch", "inner_monologue"):
            if f'"{key}"' in blob:
                raise SystemExit(f"{eid}: banned key {key}")
    return {
        "id": eid,
        "goal": goal,
        "plan": plan,
        "steps": steps,
        "outcome": outcome,
        "reward": reward,
        "meta": meta,
    }


def site(sub: str, host: str) -> str:
    if host in BANNED_HOSTS:
        raise SystemExit(f"banned host: {host}")
    return f"{sub}.{host}.example"


