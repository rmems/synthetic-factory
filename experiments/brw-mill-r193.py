def pair_for_round(n: int) -> dict:
    idx = n - CATALOG_FIRST
    if idx < 0 or idx >= len(PAIRS):
        raise SystemExit(f"no catalog entry for r{n} (first={CATALOG_FIRST} last={CATALOG_FIRST + len(PAIRS) - 1})")
    return PAIRS[idx]


def validate_pair(n: int, ok: dict, bad: dict, p: dict) -> None:
    for host in (p["ok_host"], p["bad_host"]):
        if host in BANNED_HOSTS:
            raise SystemExit(f"banned host {host}")
    seed_blob = f"{p['css']} {p['seed_ok']} {p['seed_bad']} {p['css_short']}".lower()
    for token in BANNED_CSS:
        if token in seed_blob:
            raise SystemExit(f"banned css as this-round seed: {token}")
    if ok["reward"]["success"] is not True:
        raise SystemExit("success episode not success")
    if bad["reward"]["success"] is not False:
        raise SystemExit("fail episode not fail")
    fail_blob = json.dumps(bad, ensure_ascii=False)
    if '"http_409s"' in fail_blob or fail_blob.count("409") and p["code"] == 409:
        raise SystemExit("409 fail banned")
    for rec_ in (ok, bad):
        if not (13 <= len(rec_["steps"]) <= 16):
            raise SystemExit("step count")
        if rec_["meta"]["generator"] != GEN:
            raise SystemExit("generator")
        if rec_["meta"]["round"] != n:
            raise SystemExit("round")


def write_round(n: int, staging: Path) -> None:
    p = pair_for_round(n)
    ok = build_success(n, p)
    bad = build_fail(n, p)
    validate_pair(n, ok, bad, p)
    batch = staging / f"batch-r{n:02d}.jsonl"
    notes = staging / f"NOTES-r{n:02d}.md"
    batch.write_text(
        json.dumps(ok, ensure_ascii=False) + "\n" + json.dumps(bad, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    notes.write_text(notes_for(n, p), encoding="utf-8")
    print(json.dumps({"round": n, "ids": [ok["id"], bad["id"]], "steps": [len(ok["steps"]), len(bad["steps"])], "code": p["code"], "css": p["css"]}))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--round", type=int, required=True)
    ap.add_argument("--staging", required=True)
    args = ap.parse_args()
    staging = Path(args.staging)
    if not staging.is_dir():
        print(f"staging missing: {staging}", file=sys.stderr)
        return 2
    write_round(args.round, staging)
    return 0


