def main() -> int:
    used_slugs = {ln.strip() for ln in USED_SLUGS.read_text().splitlines() if ln.strip()}
    used_stems = {ln.strip() for ln in USED_STEMS.read_text().splitlines() if ln.strip()}
    mill_text = MILL.read_text()
    mill_slugs = set(re.findall(r'slug="([^"]+)"', mill_text))
    mill_stems = set(re.findall(r'_cfg\(\s*"([^"]+)"\s*,\s*"([^"]+)"', mill_text))
    mill_stem_vals = {m[1] for m in mill_stems} | set(re.findall(r'_cmd\(\s*"([^"]+)"\s*,\s*"([^"]+)"', mill_text))
    # _cmd capture groups are slug,stem
    mill_stem_vals = {m[1] for m in re.finditer(r'_(?:cfg|cmd)\(\s*"([^"]+)"\s*,\s*"([^"]+)"', mill_text)}
    mill_stem_vals = {m.group(2) for m in re.finditer(r'_(?:cfg|cmd)\(\s*"([^"]+)"\s*,\s*"([^"]+)"', mill_text)}

    slugs = [r[0] for r in ROWS]
    stems = [r[1] for r in ROWS]
    if len(slugs) != len(set(slugs)):
        dups = [s for s in slugs if slugs.count(s) > 1]
        raise SystemExit(f"dup slugs in ROWS {set(dups)}")
    if len(stems) != len(set(stems)):
        dups = [s for s in stems if stems.count(s) > 1]
        raise SystemExit(f"dup stems in ROWS {set(dups)}")
    if len(ROWS) % 2:
        raise SystemExit(f"odd ROWS {len(ROWS)}")
    hit_slug = [s for s in slugs if s in used_slugs or s in mill_slugs]
    hit_stem = [s for s in stems if s in used_stems or s in mill_stem_vals]
    if hit_slug:
        raise SystemExit(f"slug collision {hit_slug[:8]}")
    if hit_stem:
        raise SystemExit(f"stem collision {hit_stem[:8]}")

    sibs = []
    for i in range(0, len(ROWS), 2):
        a, b = ROWS[i], ROWS[i + 1]
        pa, pb = a[0].split("-")[0], b[0].split("-")[0]
        if pa == pb:
            sibs.append(f"{a[0]} {b[0]}")
    if sibs:
        raise SystemExit("sibling first-token " + "; ".join(sibs))
        for row in (a, b):
            effect = row[5].lower()
            if effect.startswith("hid"):
                raise SystemExit(f"{row[0]} effect starts hid")
            if "leftover hid" in effect:
                raise SystemExit(f"{row[0]} leftover hid")
            if row[5].startswith("[") or "wrap 46" in row[5].lower():
                raise SystemExit(f"{row[0]} wrap")

    lines = ["\n# --- W9 unique plants (r1725+; not clones of r793-r1724) ---\n"]
    for i in range(0, len(ROWS), 2):
        a, b = ROWS[i], ROWS[i + 1]
        oa, na = str(i % 4), str(5 + (i % 5))
        ob, nb = str((i + 1) % 4), str(5 + ((i + 2) % 5))

        def call(row, *, handoff: bool, old: str, new: str) -> str:
            slug, stem, key, bad, good, effect, probe, bad_obs, good_obs, wrong, wrong_obs = row
            g = "None" if good is None else json_str(good)
            extra = ",\n         handoff=True" if handoff else ""
            return (
                f"    _cfg({json_str(slug)}, {json_str(stem)}, {json_str(key)}, {json_str(bad)}, {g},\n"
                f"         {json_str(effect)},\n"
                f"         {json_str(probe)},\n"
                f"         {json_str(bad_obs)}, {json_str(good_obs)},\n"
                f"         {json_str(wrong)},\n"
                f"         {json_str(wrong_obs)}{extra}, old={json_str(old)}, new={json_str(new)}),"
            )

        lines.append("add(\n")
        lines.append(call(a, handoff=False, old=oa, new=na) + "\n")
        lines.append(call(b, handoff=True, old=ob, new=nb) + "\n")
        lines.append(")\n")

    block = "".join(lines)
    needle = "\ndef _assert_local() -> None:\n"
    if needle not in mill_text:
        raise SystemExit("cannot find _assert_local")
    if "W9 unique plants (r1725+" in mill_text:
        raise SystemExit("W9 already present")
    mill_text = mill_text.replace(needle, block + needle, 1)
    mill_text = mill_text.replace(
        "Not a clone of r793–r1459 (whoosh-writer-leftover3d-rebuild, ",
        "Not a clone of r793–r1724 (whoosh-writer-leftover3d-rebuild, ",
    )
    mill_text = mill_text.replace(
        "Not wrap-46. Not clones of r793–r1459",
        "Not wrap-46. Not clones of r793–r1724",
    )
    MILL.write_text(mill_text)
    print(f"appended {len(ROWS)//2} pairs ({len(ROWS)} plants) catalog now includes W9")
    return 0


def json_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


if __name__ == "__main__":
    raise SystemExit(main())
