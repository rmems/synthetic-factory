def catalog_selfcheck() -> None:
    seen: set[str] = set()
    if len(PAIRS) < 20:
        raise SystemExit(f"catalog too small: {len(PAIRS)}")
    for a, b in PAIRS:
        if not a["success"] or b["success"]:
            raise SystemExit(f"pair must be success+fail: {a['slug']} / {b['slug']}")
        for spec in (a, b):
            slug = spec["slug"]
            if slug in seen:
                raise SystemExit(f"duplicate slug {slug}")
            seen.add(slug)
            blob = " ".join(
                str(spec.get(k, ""))
                for k in (
                    "slug",
                    "domain",
                    "plant",
                    "field",
                    "old",
                    "new",
                    "fail_err",
                    "plan_change",
                    "residual",
                    "vs",
                )
            ).lower()
            for needle in BANNED_SLUG_NEEDLES:
                if needle.lower() in slug or needle.lower() in blob:
                    # vs-lines may mention banned plants as contrast; only fail slug/domain
                    if needle.lower() in slug or needle.lower() in spec["domain"]:
                        raise SystemExit(f"banned needle {needle!r} in {slug}")
            if "w131" in slug or "variant v" in spec["plan_change"].lower():
                raise SystemExit(f"wrap tag leaked in {slug}")


BATCH_ROUND_RE = re.compile(r"^batch-r(\d+)\.jsonl$")
WRAP_MILL_LO = 10
WRAP_MILL_HI = 3560
STAGING_ROOT = ROOT / "outputs" / "staging" / "2026-08-19-agentic" / FACTORY_NAME
ID_SLUG_RE = re.compile(
    r"acm-r\d+(?:-b)?-([a-z0-9-]+?)(?:-w\d+)?(?:-v\d+)?(?:-w\d+)?(?:-[a-f0-9]{4})?$"
)


def _ingest_batch(path: Path, found: set[str]) -> None:
    try:
        text = path.read_text()
    except OSError:
        return
    for line in text.splitlines():
        if not line.strip():
            continue
        try:
            obj = json.loads(line)
        except json.JSONDecodeError:
            continue
        eid = str(obj.get("id", ""))
        seed = str((obj.get("meta") or {}).get("seed", ""))
        for token in (eid, seed):
            found.add(token)
        m = ID_SLUG_RE.match(eid)
        if m:
            found.add(m.group(1))


def published_slugs() -> set[str]:
    found: set[str] = set()
    if FACTORY.is_dir():
        for path in FACTORY.glob("batch-r*.jsonl"):
            m = BATCH_ROUND_RE.match(path.name)
            if m:
                n = int(m.group(1))
                if WRAP_MILL_LO <= n <= WRAP_MILL_HI:
                    continue
            _ingest_batch(path, found)
    if STAGING_ROOT.is_dir():
        for path in STAGING_ROOT.glob("*/batch-r*.jsonl"):
            _ingest_batch(path, found)
    return found


def next_free_idx(start: int = 0) -> int | None:
    existing = published_slugs()
    for i in range(start, len(PAIRS)):
        a, b = PAIRS[i]
        if a["slug"] not in existing and b["slug"] not in existing:
            return i
    return None


def last_free_idx() -> int | None:
    existing = published_slugs()
    for i in range(len(PAIRS) - 1, -1, -1):
        a, b = PAIRS[i]
        if a["slug"] not in existing and b["slug"] not in existing:
            return i
    return None


def unused_pairs() -> list[tuple[dict, dict]]:
    existing = published_slugs()
    out = []
    for pair in PAIRS:
        if pair[0]["slug"] not in existing and pair[1]["slug"] not in existing:
            out.append(pair)
    return out


def basis(s: str) -> str:
    if len(s) > 240:
        s = s[:237] + "..."
    return s


def step(n, db, name, args, obs, refl):
    db = basis(db)
    assert db.startswith(("Plan:", "Observation:", "Reflection:", "Tool call:")), db
    return {
        "n": n,
        "decision_basis": db,
        "tool_call": {"name": name, "args": args},
        "observation": obs,
        "reflection": refl,
    }


