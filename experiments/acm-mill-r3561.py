def notes_text(round_n: int, eps: list[dict], themes: list[dict], idx: int) -> str:
    coverage = 61.0 + (idx % 12) + ((round_n % 5) * 0.2)
    lines = [
        f"# api-contract-migration-factory — NOTES r{round_n} leftover unique",
        "",
        f"Novel coverage: {coverage:.1f}%",
        "",
        "## Episodes",
    ]
    for ep, th in zip(eps, themes):
        pc = th["plan_change"]
        if len(pc) > 180:
            pc = pc[:177] + "..."
        lines.append(
            f"- `{ep['id']}`: 16 steps, success={th['success']}, domain={th['domain']}, seed={th['slug']}"
        )
        lines.append("  - 429 at step 8 recovered 9; 502 at step 6 recovered 7")
        lines.append(f"  - plan change at step 13: {pc}")
        lines.append("  - edit→test→fail→re-read→fix at steps 10-13")
    lines += [
        "",
        "## decision_basis audit",
        "Every step has decision_basis starting with Plan:/Observation:/Reflection:/Tool call:, length ≤240, no thought/chain_of_thought/scratch/inner_monologue keys, no spike_events, no sim_or_real real, no Spikenaut. Generator grok-4.6. IDs leftover unique without wrap tags.",
        "",
        "## Mix",
        f"Success: {[e['id'] for e, t in zip(eps, themes) if t['success']]}. Realistic failure/handoff: {[e['id'] for e, t in zip(eps, themes) if not t['success']]}.",
        "",
        "## Realism / weak recovery paths",
        "Noise recoveries are backoff+retry or local fixture cache. First patches are domain-plausible and fail closed. Designed traces — not live executions. BAN r3560 422-vs-400 / 207-multistatus and prior w131 cartesian. BAN r01 discriminator.mapping miss.",
        "",
        f"## vs wrap mill / prior leftover",
        f"- idx={idx} pair slugs {[t['slug'] for t in themes]} vs {[t['vs'] for t in themes]}",
        "",
        "## Step counts",
    ]
    for ep in eps:
        lines.append(f"- {ep['id']}: 16 (required 12–20)")
    lines.append("")
    return "\n".join(lines)


def write_round(round_n: int, staging: Path, idx: int | None = None) -> None:
    catalog_selfcheck()
    if idx is None:
        idx = next_free_idx()
        if idx is None:
            raise SystemExit("catalog exhausted")
    if idx < 0 or idx >= len(PAIRS):
        raise SystemExit(f"no catalog pair for idx={idx} (len={len(PAIRS)})")
    t1, t2 = PAIRS[idx]
    existing = published_slugs()
    for spec in (t1, t2):
        if spec["slug"] in existing:
            raise SystemExit(f"slug {spec['slug']} already published; refuse clone")
    e1 = build_episode(round_n, t1)
    e2 = build_episode(round_n, t2)
    for e in (e1, e2):
        blob = json.dumps(e)
        for banned in BANNED_BLOB:
            if f'"{banned}"' in blob:
                raise SystemExit(f"banned key {banned} in {e['id']}")
        assert e["meta"]["generator"] == GEN
        assert len(e["steps"]) == 16
        assert "[variant" not in e["goal"]
        assert "-w131" not in e["id"]
        for s in e["steps"]:
            assert 1 <= len(s["decision_basis"]) <= 240
    batch = staging / f"batch-r{round_n:02d}.jsonl"
    notes = staging / f"NOTES-r{round_n:02d}.md"
    batch.write_text(
        json.dumps(e1, ensure_ascii=False) + "\n" + json.dumps(e2, ensure_ascii=False) + "\n"
    )
    notes.write_text(notes_text(round_n, [e1, e2], [t1, t2], idx))
    print(
        json.dumps(
            {
                "round": round_n,
                "idx": idx,
                "ids": [e1["id"], e2["id"]],
                "steps": [16, 16],
                "bytes": batch.stat().st_size,
            }
        )
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--round", type=int, required=True)
    ap.add_argument("--staging", required=True)
    ap.add_argument("--idx", type=int, default=None)
    args = ap.parse_args()
    write_round(args.round, Path(args.staging), args.idx)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
