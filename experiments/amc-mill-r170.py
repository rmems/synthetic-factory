def clip(text: str, n: int = 240) -> str:
    text = " ".join(str(text).split())
    if len(text) <= n:
        return text
    return text[: n - 1].rstrip() + "…"


def step(n: int, basis: str, name: str, args: dict, obs: str) -> dict:
    basis = clip(basis)
    prefix = basis.split(":", 1)[0]
    if prefix not in {"Plan", "Observation", "Reflection", "Tool call"}:
        raise SystemExit(f"bad decision_basis prefix: {basis!r}")
    if len(basis) > 240:
        raise SystemExit(f"decision_basis too long ({len(basis)}): {basis}")
    return {
        "n": n,
        "decision_basis": basis,
        "tool_call": {"name": name, "args": args},
        "observation": obs,
    }


def bash(n: int, basis: str, cmd: str, obs: str) -> dict:
    return step(n, basis, "bash", {"command": cmd}, obs)


def read(n: int, basis: str, path: str, obs: str) -> dict:
    return step(n, basis, "read", {"path": path}, obs)


def edit(n: int, basis: str, path: str, old: str, new: str, obs: str) -> dict:
    return step(n, basis, "edit", {"path": path, "old": old, "new": new}, obs)


def write_tool(n: int, basis: str, path: str, contents: str, obs: str) -> dict:
    return step(n, basis, "write", {"path": path, "contents": contents}, obs)


def _check_slug(slug: str) -> None:
    low = slug.lower()
    for needle in BANNED_SLUG_NEEDLES:
        if needle in low:
            raise SystemExit(f"banned slug needle {needle!r} in {slug}")


def build_episode(round_n: int, spec: dict) -> dict:
    slug = spec["slug"]
    _check_slug(slug)
    eid = f"amc-r{round_n}-{slug}"
    fail = bool(spec["fail"])
    mod = spec["mod"]
    pin = spec["pin"]
    src = f"src/{mod}.py"
    testp = f"tests/test_{mod}.py"
    gate = spec["gate"]
    chatter = spec["chatter"]
    leftover = spec["leftover"]
    first_name = spec["first_name"]
    fix_name = spec["fix_name"]
    src_bad = spec["src_bad"]
    first_new = spec["first_new"]
    fix_body = spec["fix"]
    test_fn = spec["test_fn"]
    chatter_fn = spec["chatter_fn"]
    leftover_fn = spec["leftover_fn"]

    src_obs = (
        f"def compact(self):\n"
        f"    for i in self.items:\n"
        f"        {src_bad}\n"
    )
    test_obs = (
        f"def {test_fn}():\n"
        f"    s = Store.ep()\n"
        f"    {spec['setup']}\n"
        f"    s.compact()\n"
        f"    assert {spec['assert_expr']}\n"
    )
    dump_obs = spec["dump"]
    gate_fail = f"FAILED - AssertionError: {spec['gate_err']}"
    first_retest = (
        f"FAILED {testp}::{chatter_fn} - {spec['chatter_err']}\n"
        f"passed {testp}::{test_fn}\n"
        f"1 failed, 1 passed"
    )
    plant_pass = "2 passed"
    if fail:
        suite_obs = (
            f"{testp}::{leftover_fn} FAILED\n"
            f"3 passed, 1 failed"
        )
        confirm = "True"
        xfail_obs = "marked xfail"
        residual_obs = f"xfail {leftover_fn} still present"
        final_obs = f"3 passed, 1 xfailed\nHANDOFF={leftover}"
        outcome = (
            f"{spec['surface']} dropped the pin. {first_name} left chatter. "
            f"Plan change: {fix_name}. Pin + chatter 2/2. Partial: {leftover} xfail."
        )
        reward = {
            "success": False,
            "plan_changes": 1,
            "tests_passed": 2,
            "xfailed": 1,
            "handoff": 1,
            "cost_steps": 16,
        }
    else:
        suite_obs = "7 passed"
        confirm = "True"
        xfail_obs = f"NO_{first_name.upper().replace('-', '_')}"
        residual_obs = "7 tests, no xfail"
        final_obs = "OK"
        outcome = (
            f"{spec['surface']} dropped the pin. {first_name} dropped chatter. "
            f"Plan change: {fix_name}. Pin + chatter + 5 more 7/7. Pin preserved."
        )
        reward = {
            "success": True,
            "plan_changes": 1,
            "tests_passed": 7,
            "cost_steps": 16,
        }

    goal = (
        f"{HOST} {spec['surface']} {spec['bug']}. Pin {pin} stays. "
        f"{testp} is the gate."
    )
    plan = spec["plan"]

    steps = [
        bash(
            1,
            f"Plan: inspect {spec['surface']} compact rewriting or dropping {pin} vs pin surviving before changing code.",
            f"rg -n '{mod}|{pin}|compact' src tests | head -n 40",
            f"{src}: def compact\n{src}: {src_bad}\n{testp}: def {test_fn}",
        ),
        read(
            2,
            f"Observation: compact hits pins (step 1). Read {src}.",
            src,
            src_obs,
        ),
        read(
            3,
            f"Observation: pin {pin} must survive (step 2). Read the gate.",
            testp,
            test_obs,
        ),
        bash(
            4,
            f"Observation: chatter may still compact (step 3). Run gate.",
            f"pytest -q {testp}::{test_fn}",
            gate_fail,
        ),
        bash(
            5,
            f"Observation: pin lost (step 4). Dump leftover state.",
            f"python3 -c 'from src.{mod} import Store; s=Store.ep(); s.compact(); print(s.items)'",
            dump_obs,
        ),
        edit(
            6,
            f"Plan: first apply — {spec['first_plan']}.",
            src,
            src_bad,
            first_new,
            f"{src}: {first_name}",
        ),
        bash(
            7,
            f"Observation: {first_name} (step 6). Re-run plant + budget.",
            f"pytest -q {testp}",
            first_retest,
        ),
        write_tool(
            8,
            f"Reflection: plan change after {first_name} — {spec['plan_change']}.",
            src,
            fix_body,
            f"wrote {fix_name}",
        ),
        bash(
            9,
            f"Observation: {fix_name} (step 8). Re-run plant + size.",
            f"pytest -q {testp}::{test_fn} {testp}::{chatter_fn}",
            plant_pass,
        ),
        bash(
            10,
            f"Observation: 2/2 (step 9). Full {mod} suite.",
            f"pytest -q {testp}",
            suite_obs,
        ),
    ]
    if fail:
        steps += [
            read(
                11,
                f"Observation: {leftover} later (step 10). Read leftover.",
                src,
                f"# {leftover} later",
            ),
            edit(
                12,
                f"Observation: {leftover} leftover (step 11). xfail leftover; {pin} is the plant.",
                testp,
                f"def {leftover_fn}():",
                f"@pytest.mark.xfail(reason='{leftover} is later')\ndef {leftover_fn}():",
                xfail_obs,
            ),
            bash(
                13,
                "Observation: leftover xfails (step 12). Re-run plant + size.",
                f"pytest -q {testp}::{test_fn} {testp}::{chatter_fn}",
                plant_pass,
            ),
            bash(
                14,
                f"Observation: pin intact (step 13). Confirm pin.",
                f"python3 -c 'from src.{mod} import Store; s=Store.ep(); s.compact(); print({spec['confirm']})'",
                confirm,
            ),
            read(
                15,
                f"Observation: pin held (step 14). Residual: {leftover}.",
                testp,
                residual_obs,
            ),
            bash(
                16,
                f"Observation: leftover out of scope (step 15). Leave xfail; hand off {leftover}.",
                f"pytest -q {testp}; echo HANDOFF={leftover}",
                final_obs,
            ),
        ]
    else:
        steps += [
            bash(
                11,
                f"Observation: 7/7 (step 10). Confirm pin after compact.",
                f"python3 -c 'from src.{mod} import Store; s=Store.ep(); s.compact(); print({spec['confirm']})'",
                confirm,
            ),
            read(
                12,
                f"Observation: {pin} preserved (step 11). Residual: {leftover} later.",
                src,
                f"# {leftover} later",
            ),
            bash(
                13,
                f"Observation: {fix_name} is the plant (step 12). Grep leftover first-apply.",
                f"rg -n '{first_name}' src || echo NO_{first_name.upper().replace('-', '_')}",
                xfail_obs,
            ),
            bash(
                14,
                "Observation: first-apply gone (step 13). Re-run full suite.",
                f"pytest -q {testp} tests/test_pins.py::test_{mod}_helper",
                "8 passed",
            ),
            read(
                15,
                "Observation: still green (step 14). Pin preserved.",
                testp,
                residual_obs,
            ),
            bash(
                16,
                "Observation: 7/7 (step 15). No xfail.",
                f"python3 -c 'from src.{mod} import Store; s=Store.ep(); s.compact(); assert {spec['confirm']}'; echo OK",
                final_obs,
            ),
        ]
    if len(steps) != 16:
        raise SystemExit(f"{eid} expected 16 steps, got {len(steps)}")
    return {
        "id": eid,
        "goal": goal,
        "plan": plan,
        "steps": steps,
        "outcome": outcome,
        "reward": reward,
        "meta": {"factory": FACTORY, "round": round_n, "generator": GEN},
    }


