def used() -> tuple[set[str], set[str], set[str]]:
    slugs: set[str] = set()
    gs: set[str] = set()
    ms: set[str] = set()
    for p in (ROOT / "experiments").glob("iac-mill-*.py"):
        text = p.read_text()
        slugs.update(re.findall(r"'([a-z0-9-]+-vs-old)'", text))
        slugs.update(re.findall(r"'([a-z0-9-]+-old-leftover)'", text))
        gs.update(re.findall(r"'g': '([a-z0-9]+)'", text))
        ms.update(re.findall(r"'m': '([a-z0-9]+)'", text))
        for mm in re.finditer(
            r"\(\s*'[a-z0-9-]+-vs-old'\s*,\s*'([a-z0-9]+)'\s*,\s*'([a-z0-9]+)'",
            text,
        ):
            gs.add(mm.group(1))
            ms.add(mm.group(2))
        for mm in re.finditer(
            r"\(\s*'[a-z0-9-]+-vs-old'\s*,\s*'([a-z0-9]+)'\s*,",
            text,
        ):
            gs.add(mm.group(1))
    if FACTORY.is_dir():
        for batch in FACTORY.glob("batch-r*.jsonl"):
            for line in batch.read_text().splitlines():
                if not line.strip():
                    continue
                rec = json.loads(line)
                i = rec.get("id", "")
                m = re.match(r"iac-r\d+-(.+)$", i)
                if m:
                    slugs.add(m.group(1))
    return slugs, gs, ms


