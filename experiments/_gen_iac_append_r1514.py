def row_for(tool: tuple[str, str, str, str, str], g: str, m: str) -> dict:
    slug, _m0, product, bin_name, current = tool
    old = f"{current}.bak"
    oldj = f"jobs-{current}.bak"
    leftover = f"{old} web-old"
    leftover_j = f"{oldj} jobs-old"
    return {
        "s": f"{slug}-vs-old",
        "g": g,
        "m": m,
        "product": product,
        "leftover": leftover,
        "leftover_j": leftover_j,
        "fail": f"{bin_name} still uses leftover {leftover}",
        "wrong": f"{bin_name} leftover",
        "fix": f"{bin_name} apply {current}",
        "bin_name": bin_name,
        "current": current,
        "old": old,
        "oldj": oldj,
    }


def emit() -> None:
    used_slugs, used_gs, used_ms = used()
    mill = MILL.read_text()
    marker = "]\n\nCLI: list[tuple[dict, dict]] = [tool_pair(**row) for row in CLI_SPEC]"
    if marker not in mill:
        raise SystemExit("CLI_SPEC close marker missing")
    kept: list[dict] = []
    skipped = 0
    for tool in TOOLS:
        slug = f"{tool[0]}-vs-old"
        leftover_slug = f"{tool[0].replace('-vs-old', '')}-old-leftover"
        # leftover_pair slug is s.replace('-vs-old','-old-leftover')
        fail_slug = slug.replace("-vs-old", "-old-leftover")
        if any(bit in slug for bit in BANNED_BITS) or "ytt" in slug:
            skipped += 1
            continue
        if slug in used_slugs or fail_slug in used_slugs:
            skipped += 1
            continue
        m = tool[1]
        if m in used_ms:
            m2 = m + "z"
            if m2 in used_ms:
                m2 = m + "y"
            if m2 in used_ms:
                skipped += 1
                continue
            m = m2
        kept.append((tool, m))
        used_slugs.add(slug)
        used_slugs.add(fail_slug)
        used_ms.add(m)
    gs = g_pool(set(used_gs), len(kept))
    rows = [row_for(tool, g, m) for (tool, m), g in zip(kept, gs)]
    insert = "".join(f"    {row!r},\n" for row in rows)
    new = mill.replace(marker, insert + marker, 1)
    tmp = MILL.with_suffix(".py.tmp")
    tmp.write_text(new)
    tmp.replace(MILL)
    print(
        json.dumps(
            {
                "appended": len(rows),
                "skipped": skipped,
                "first": rows[0]["s"] if rows else None,
                "last": rows[-1]["s"] if rows else None,
            }
        )
    )


if __name__ == "__main__":
    emit()
