def _published_slugs() -> set[str]:
    """Only scan r1278+; this catalog was uniqueness-checked against r793–r1277."""
    used: set[str] = set()
    if not FACTORY_DIR.exists():
        return used
    for path in FACTORY_DIR.glob("batch-r*.jsonl"):
        stem = path.stem  # batch-r1278
        try:
            n = int(stem.split("r", 1)[1])
        except ValueError:
            continue
        if n < _CATALOG_START:
            continue
        for line in path.read_text().splitlines():
            if not line.strip():
                continue
            rec = json.loads(line)
            match = re.match(r"gor-r\d+-(.+)$", rec.get("id", ""))
            if match:
                used.add(match.group(1))
    return used


def cmdplant(
    *,
    slug: str,
    repo: str,
    marker: str,
    old: str,
    new: str,
    stem: str,
    knob: str,
    effect: str,
    map_cmd: str,
    map_obs: str,
    wrong: str,
    wrong_obs: str,
    rec_cmd: str,
    rec_obs: str,
    left_cmd: str,
    left_obs: str,
    handoff: str | None = None,
    issue_t: str | None = None,
    ci_obs: str | None = None,
    ci_probe: str | None = None,
) -> dict:
    recover = f"Recover leftover {knob}"
    mix = f"leftover {knob} {effect}"
    w0 = wrong.split("&&")[0].strip()[:80]
    map_b = _trim(f"Plan: map leftover {knob}.")
    wrong_b = _trim(f"Observation: leftover {knob} survived. First wrong move: {w0}.")
    rec_b = _trim(f"Plan: {recover}.")
    if handoff:
        return leftover_plant(
            slug=slug,
            repo=repo,
            marker=marker,
            old=old,
            new=new,
            stem=stem,
            knob=knob,
            effect=effect,
            mix=mix,
            map_cmd=map_cmd,
            map_obs=map_obs,
            map_b=map_b,
            wrong_cmd=wrong,
            wrong_obs=wrong_obs,
            wrong_b=wrong_b,
            rec_cmd=rec_cmd,
            rec_obs=rec_obs,
            rec_b=rec_b,
            left_cmd=left_cmd,
            left_obs=left_obs,
            left_b=_trim(f"Observation: local leftover {knob} recovered; CI still set."),
            recover=recover,
            refl=_trim(
                f"Reflection: leftover {knob} survived. Plan change: PR the {new}; hand off CI."
            ),
            handoff=handoff,
            issue_t=issue_t or f"CI leftover still has {knob}",
            issue_b=f"PR {{pr}}. Fix leftover {knob} on CI. INC-{{inc}}.",
            handoff_probe=ci_probe
            or f"ssh ci-runner 'echo leftover; {left_cmd}'",
            handoff_probe_obs=ci_obs or "leftover",
            checks=f"unit pass\n{stem}-ci fail ({knob})\n{{\"mergeStateStatus\":\"BLOCKED\"}}",
        )
    return leftover_plant(
        slug=slug,
        repo=repo,
        marker=marker,
        old=old,
        new=new,
        stem=stem,
        knob=knob,
        effect=effect,
        mix=mix,
        map_cmd=map_cmd,
        map_obs=map_obs,
        map_b=map_b,
        wrong_cmd=wrong,
        wrong_obs=wrong_obs,
        wrong_b=wrong_b,
        rec_cmd=rec_cmd,
        rec_obs=rec_obs,
        rec_b=rec_b,
        left_cmd=left_cmd,
        left_obs=left_obs,
        left_b=_trim(f"Observation: leftover {knob} recovered."),
        recover=recover,
        refl=_trim(
            f"Reflection: leftover {knob} survived. Plan change: recover/{stem}-{new}."
        ),
    )


