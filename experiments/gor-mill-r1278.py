        "\n"
        f"Novel coverage: {cov}%\n"
        "\n"
        "## Episodes\n"
        f"- `{a['id']}`: 14 steps, success=True\n"
        "  - plan change at step 7\n"
        f"- `{b['id']}`: 14 steps, success=False\n"
        "  - plan change at step 7\n"
        "\n"
        f"Success: ['{a['id']}']. Partial/handoff: ['{b['id']}'].\n"
