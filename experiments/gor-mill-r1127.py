def leftover_plant(
    *,
    slug: str,
    repo: str,
    marker: str,
    old: str,
    new: str,
    stem: str,
    knob: str,
    effect: str,
    mix: str,
    map_cmd: str,
    map_obs: str,
    map_b: str,
    wrong_cmd: str,
    wrong_obs: str,
    wrong_b: str,
    rec_cmd: str,
    rec_obs: str,
    rec_b: str,
    left_cmd: str,
    left_obs: str,
    left_b: str,
    recover: str,
    refl: str,
    handoff: str | None = None,
    issue_t: str | None = None,
    issue_b: str | None = None,
    handoff_probe: str | None = None,
    handoff_probe_obs: str | None = None,
    checks: str | None = None,
) -> dict:
    if handoff:
        goal = (
            f"On {repo}, leftover {knob} {effect}. {recover}, land {marker}={new}. "
            "CI still set. INC-{inc}."
        )
        plan = f"Prove leftover {knob}, recover, hand off CI."
        out = (
            f"{recover} leftover {knob}; {marker}={new} on PR {{pr}}. "
            "CI still set. Issue {issue}. INC-{inc}."
        )
        cmt = (
            f"HANDOFF issue {{issue}}. {recover} leftover {knob} on CI. "
            "Do not force-push main."
        )
        body = (
            f"leftover {knob} {effect}. Recovered locally. CI still set. INC-{{inc}}."
        )
    else:
        goal = (
            f"On {repo}, leftover {knob} {effect}. {recover}, land {marker}={new}. "
            "INC-{inc}."
        )
        plan = f"Prove leftover {knob}, recover, land {new}."
        out = (
            f"{recover} leftover {knob}. {marker}={new} as {{sha}} / 2 tests / "
            "PR {pr}. INC-{inc}."
        )
        cmt = f"{recover} leftover {knob}. Do not force-push main."
        body = f"leftover {knob} {effect}. {recover}. INC-{{inc}}."
    if "leftover hid" in goal.lower():
        raise SystemExit(f"{slug} leftover hid in goal")
    if goal.startswith("["):
        raise SystemExit(f"{slug} wrap prefix")
    spec = plant(
        slug=slug,
        repo=repo,
        marker=marker,
        old=old,
        new=new,
        stem=stem,
        mix=mix,
        map_cmd=map_cmd,
        map_obs=map_obs,
        map_b=map_b,
        wrong_cmd=wrong_cmd,
        wrong_obs=wrong_obs,
        wrong_b=wrong_b,
        rec_cmd=rec_cmd,
        rec_obs=rec_obs,
        rec_b=rec_b,
        left_cmd=left_cmd,
        left_obs=left_obs,
        left_b=left_b,
        goal=goal,
        plan=plan,
        out=out,
        refl=refl,
        cmt=cmt,
        title=f"{marker}={new}",
        body=body,
        commit=f"fix: {marker}={new} after leftover {knob} recover (INC-{{inc}})",
        handoff=handoff,
        issue_t=issue_t,
        issue_b=issue_b,
        handoff_probe=handoff_probe,
        handoff_probe_obs=handoff_probe_obs,
        checks=checks,
    )
    for key in ("map_b", "wrong_b", "rec_b", "left_b", "refl"):
        if len(spec[key]) > 240:
            raise SystemExit(f"{slug} {key} {len(spec[key])} > 240")
        if "Plan change" not in spec["refl"]:
            raise SystemExit(f"{slug} refl missing Plan change")
    return spec


