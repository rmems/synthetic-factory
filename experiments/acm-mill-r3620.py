def catalog_selfcheck() -> None:
    seen: set[str] = set()
    if len(PAIRS) < 16:
        raise SystemExit(f"catalog too small: {len(PAIRS)}")
    for a, b in PAIRS:
        if not a["success"] or b["success"]:
            raise SystemExit(f"pair must be success+fail: {a['slug']} / {b['slug']}")
        for spec in (a, b):
            slug = spec["slug"]
            if slug in seen:
                raise SystemExit(f"duplicate slug {slug}")
            if slug in BANNED_PRIOR:
                raise SystemExit(f"prior mill slug leaked {slug}")
            seen.add(slug)
            if "w131" in slug:
                raise SystemExit(f"wrap tag leaked in {slug}")
            for needle in ("422-vs-400", "207-multistatus", "w131"):
                if needle in slug or needle in spec["domain"]:
                    raise SystemExit(f"banned {needle} in {slug}")


def next_free_idx(start: int = 0) -> int | None:
    existing = published_slugs()
    for i in range(start, len(PAIRS)):
        a, b = PAIRS[i]
        if a["slug"] not in existing and b["slug"] not in existing:
            return i
    return None


def unused_pairs() -> list[tuple[dict, dict]]:
    existing = published_slugs()
    return [
        pair
        for pair in PAIRS
        if pair[0]["slug"] not in existing and pair[1]["slug"] not in existing
    ]


def write_round(round_n: int, staging: Path, idx: int | None = None) -> None:
    catalog_selfcheck()
    if idx is None:
        idx = next_free_idx()
        if idx is None:
            raise SystemExit("catalog exhausted")
    if idx < 0 or idx >= len(PAIRS):
        raise SystemExit(f"no catalog pair for idx={idx} (len={len(PAIRS)})")
    t1, t2 = PAIRS[idx]
    existing = published_slugs()
    for spec in (t1, t2):
        if spec["slug"] in existing:
            raise SystemExit(f"slug {spec['slug']} already published; refuse clone")
    e1 = build_episode(round_n, t1)
    e2 = build_episode(round_n, t2)
    for e in (e1, e2):
        blob = json.dumps(e)
        for banned in BANNED_BLOB:
            if f'"{banned}"' in blob:
                raise SystemExit(f"banned key {banned} in {e['id']}")
        assert e["meta"]["generator"] == GEN
        assert len(e["steps"]) == 16
        assert "[variant" not in e["goal"]
        assert "-w131" not in e["id"]
        for s in e["steps"]:
            assert 1 <= len(s["decision_basis"]) <= 240
    batch = staging / f"batch-r{round_n:02d}.jsonl"
    notes = staging / f"NOTES-r{round_n:02d}.md"
    batch.write_text(
        json.dumps(e1, ensure_ascii=False) + "\n" + json.dumps(e2, ensure_ascii=False) + "\n"
    )
    notes.write_text(notes_text(round_n, [e1, e2], [t1, t2], idx))
    print(
        json.dumps(
            {
                "round": round_n,
                "idx": idx,
                "ids": [e1["id"], e2["id"]],
                "steps": [16, 16],
                "bytes": batch.stat().st_size,
                "catalog": "r3620",
            }
        )
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--round", type=int, required=True)
    ap.add_argument("--staging", required=True)
    ap.add_argument("--idx", type=int, default=None)
    args = ap.parse_args()
    write_round(args.round, Path(args.staging), args.idx)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
