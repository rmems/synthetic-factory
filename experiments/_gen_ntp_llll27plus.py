def main() -> None:
    waves = ((27, S27, L27), (28, S28, L28), (29, S29, L29), (30, S30, L30))
    for n, S, L in waves:
        stems = [r[1] for r in S] + [r[1] for r in L]
        if len(stems) != len(set(stems)):
            dups = [x for x in stems if stems.count(x) > 1]
            raise SystemExit(f"dup stems wave {n}: {sorted(set(dups))}")
        slugs = [r[0] for r in S] + [r[0] for r in L]
        if len(slugs) != len(set(slugs)):
            raise SystemExit(f"dup names wave {n}")
        for name, *_rest in S + L:
            if any(tok in name for tok in ("html", "png", "svg", "matplotlib", "plotly", "dnsmasq", "git-lfs")):
                raise SystemExit(f"banned token in {n} {name}")
        g.write_wave(n, S, L)
    print("wrote mills 27-30")


if __name__ == "__main__":
    main()
