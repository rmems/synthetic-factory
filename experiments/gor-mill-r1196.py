def generate_round(round_n: int):
    idx, sa, sb = pick_pair(round_n)
    published = _r1127._published_slugs()
    batch_exists = (FACTORY_DIR / f"batch-r{round_n}.jsonl").exists()
    for spec in (sa, sb):
        if spec["slug"] in published and not batch_exists:
            raise SystemExit(f"clone of published slug {spec['slug']}")
    pr_a = _r1127.PR0 + 3200 + 2 * idx
    pr_b = _r1127.PR0 + 3200 + 2 * idx + 1
    issue = _r1127.ISSUE0 + 3200 + idx
    inc_a = f"{round_n}3"
    inc_b = f"{round_n}8"
    a = _r1127._r1111._r1046.build_episode(
        round_n, sa, success=True, pr=pr_a, issue=None, inc=inc_a
    )
    b = _r1127._r1111._r1046.build_episode(
        round_n, sb, success=False, pr=pr_b, issue=issue, inc=inc_b
    )
    banned = ("thought", "chain_of_thought", "scratch", "inner_monologue", "spike_events")
    for ep in (a, b):
        blob = _json.dumps(ep)
        for key in banned:
            if f'"{key}"' in blob:
                raise SystemExit(f"{ep['id']} contains banned key {key}")
        if "wrap 46" in blob.lower() or "wrap-46" in blob.lower():
            raise SystemExit(f"{ep['id']} wrap-46")
        if ep["id"].startswith("sir-"):
            raise SystemExit(f"{ep['id']} sir- id")
        if ep["goal"].startswith("["):
            raise SystemExit(f"{ep['id']} wrap prefix goal")
        if "sim_or_real" in blob and _re.search(r'"sim_or_real"\s*:\s*"real"', blob):
            raise SystemExit(f"{ep['id']} sim_or_real real")
        if "INC-INC-" in blob:
            raise SystemExit(f"{ep['id']} double INC prefix")
        if not (12 <= len(ep["steps"]) <= 18):
            raise SystemExit(f"{ep['id']} {len(ep['steps'])} steps")
    if a["reward"]["success"] == b["reward"]["success"]:
        raise SystemExit("batch must mix success + partial")
    return [a, b], notes_for(round_n, a, b, sa, sb)


def write_round(round_n: int, staging, write_notes: bool) -> None:
    staging = Path(staging)
    eps, notes = generate_round(round_n)
    batch = staging / f"batch-r{round_n:02d}.jsonl"
    with batch.open("w") as handle:
        for ep in eps:
            handle.write(_json.dumps(ep, ensure_ascii=True, separators=(",", ":")) + "\n")
    if write_notes:
        nfile = staging / f"NOTES-r{round_n:02d}.md"
        nfile.write_text(notes)
        print(f"wrote {batch} ({len(eps)} eps) {nfile}", file=sys.stderr)
    else:
        print(f"wrote {batch} ({len(eps)} eps) notes skipped", file=sys.stderr)


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("--round", type=int, required=True)
    parser.add_argument("--staging", required=True)
    parser.add_argument("--notes", action="store_true", default=True)
    parser.add_argument("--no-notes", action="store_true")
    args = parser.parse_args()
    write_round(args.round, args.staging, write_notes=not args.no_notes)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
