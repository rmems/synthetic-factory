def _gc_pair(i: int, stem: str, noun: str, attr: str) -> tuple[dict, dict]:
    short = f"q4g{i:02d}"
    pin = f"NEVER_Q4G{i:02d}_PIN"
    pin_k = f"NEVER_KEEP_Q4G{i:02d}"
