def _load_ext() -> None:
    for name in (
        "dbc-mill-r402-plants.py",
        "dbc-mill-r470-plants.py",
        "dbc-mill-r502-plants.py",
    ):
        path = HERE / name
        if not path.exists():
            continue
        spec = importlib.util.spec_from_file_location(name.replace(".", "_"), path)
        mod = importlib.util.module_from_spec(spec)
        assert spec.loader is not None
        spec.loader.exec_module(mod)
        extra = mod.build(lang, left)
        if extra:
            PAIRS.extend(extra)


_load_ext()


def _identity(spec: dict) -> str:
    return " ".join(
        str(spec.get(k, ""))
        for k in ("slug", "harbor", "env", "tool", "leftover", "token", "cache_id")
    ).lower()


def guard_extra(spec: dict) -> None:
    identity = _identity(spec)
    for needle in BANNED_EXTRA:
        if needle in identity:
            raise SystemExit(f"banned needle {needle!r} in plant identity {identity!r}")


def catalog_selfcheck() -> None:
    slugs: list[str] = []
    for suc, leftp in PAIRS:
        guard_extra(suc)
        guard_extra(leftp)
        slugs.extend([suc["slug"], leftp["slug"]])
    dup = {s for s in slugs if slugs.count(s) > 1}
    if dup:
        raise SystemExit(f"duplicate catalog slugs: {sorted(dup)}")
    existing = published_slugs()
    unused = [s for s in slugs if s not in existing]
    if not unused:
        raise SystemExit("catalog exhausted (all slugs published)")


def write_round(round_n: int, staging: Path, idx: int | None = None) -> None:
    if idx is None:
        raise SystemExit("catalog idx required (do not bind to a stolen round)")
    if idx < 0 or idx >= len(PAIRS):
        raise SystemExit(f"no catalog pair for idx={idx} (len={len(PAIRS)})")
    suc, leftp = PAIRS[idx]
    existing = published_slugs()
    for spec in (suc, leftp):
        guard_extra(spec)
        if spec["slug"] in existing:
            raise SystemExit(f"slug {spec['slug']} already published; refuse clone")
    srec = success_episode(round_n, suc)
    lrec = leftover_episode(round_n, leftp)
    if srec["id"] in existing or lrec["id"] in existing:
        raise SystemExit(f"id collision {srec['id']} / {lrec['id']}")
    for key in ("thought", "chain_of_thought", "scratch", "inner_monologue", "spike_events"):
        if key in srec or key in lrec:
            raise SystemExit(f"forbidden key {key}")
        blob = json.dumps(srec) + json.dumps(lrec)
        if f'"{key}"' in blob:
            raise SystemExit(f"forbidden key {key} nested")
    if '"sim_or_real": "real"' in json.dumps(srec) or '"sim_or_real": "real"' in json.dumps(lrec):
        raise SystemExit("sim_or_real real forbidden")
    batch = staging / f"batch-r{round_n:02d}.jsonl"
    notes = staging / f"NOTES-r{round_n:02d}.md"
    batch.write_text(
        json.dumps(srec, separators=(",", ":")) + "\n" + json.dumps(lrec, separators=(",", ":")) + "\n"
    )
    notes.write_text(notes_for(round_n, suc, leftp, srec, lrec))
    print(
        json.dumps(
            {
                "round": round_n,
                "idx": idx,
                "ids": [srec["id"], lrec["id"]],
                "steps": [srec["reward"]["cost_steps"], lrec["reward"]["cost_steps"]],
                "bytes": batch.stat().st_size,
            }
        )
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--round", type=int, required=True)
    ap.add_argument("--staging", required=True)
    ap.add_argument("--idx", type=int, required=True)
    ap.add_argument("--selfcheck", action="store_true")
    args = ap.parse_args()
    if args.selfcheck:
        catalog_selfcheck()
    write_round(args.round, Path(args.staging), args.idx)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
