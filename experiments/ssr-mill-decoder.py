def build_round(rnd: int, idx: int) -> tuple[list[dict], str]:
    if idx < 0 or idx >= len(PAIRS):
        raise SystemExit(f"idx {idx} outside catalog 0..{len(PAIRS) - 1}")
    suc, fail = PAIRS[idx]
    used = published_slugs()
    for spec in (suc, fail):
        if spec["slug"] in used:
            raise SystemExit(f"slug already published: {spec['slug']}")
    suc_n = 16 if idx % 2 else 14
    fail_n = 15 if idx % 3 else 16
    suc_ep = success_episode(rnd, suc, suc_n)
    fail_ep = fail_episode(rnd, fail, fail_n)
    for ep in (suc_ep, fail_ep):
        n = len(ep["steps"])
        if n < 14 or n > 16:
            raise SystemExit(f"{ep['id']} has {n} steps, want 14-16")
        ep["reward"]["cost_steps"] = n
        for s in ep["steps"]:
            basis = s["decision_basis"]
            prefix = basis.split(":", 1)[0]
            if prefix not in {"Plan", "Observation", "Reflection", "Tool call"}:
                raise SystemExit(f"{ep['id']} bad prefix {basis!r}")
            if len(basis) > 240:
                raise SystemExit(f"{ep['id']} basis too long ({len(basis)})")
    notes = notes_md(rnd, idx, suc, fail, suc_ep, fail_ep)
    return [suc_ep, fail_ep], notes


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--round", type=int, required=True)
    ap.add_argument("--staging", required=True)
    ap.add_argument("--idx", type=int, required=True)
    args = ap.parse_args()
    rnd = args.round
    staging = Path(args.staging)
    recs, notes = build_round(rnd, args.idx)
    batch = staging / f"batch-r{rnd:02d}.jsonl"
    notes_path = staging / f"NOTES-r{rnd:02d}.md"
    with batch.open("w") as handle:
        for rec in recs:
            handle.write(json.dumps(rec, ensure_ascii=True) + "\n")
    notes_path.write_text(notes)
    print(
        json.dumps(
            {
                "round": rnd,
                "idx": args.idx,
                "ids": [r["id"] for r in recs],
                "steps": [len(r["steps"]) for r in recs],
                "batch": str(batch),
                "notes": str(notes_path),
            }
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
