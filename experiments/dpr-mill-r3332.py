        spec["pass_obs"] = spec["pass_obs"] + "\nverify reconcile valid pass"
        spec["close_obs"] = spec["close_obs"] + " etl pipeline schema late-data repair verified."
        spec["outcome"] = (
            spec["outcome"] + " etl pipeline late-data schema repair verified; tests pass."
        )
