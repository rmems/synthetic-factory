def clip(text: str, n: int = 240) -> str:
    text = " ".join(str(text).split())
    if len(text) <= n:
        return text
    return text[: n - 1].rstrip() + "…"


def step(n: int, basis: str, name: str, args: dict, obs: str, reflection: str | None = None) -> dict:
    basis = clip(basis)
    prefix = basis.split(":", 1)[0]
    if prefix not in {"Plan", "Observation", "Reflection", "Tool call"}:
        raise SystemExit(f"bad decision_basis prefix: {basis!r}")
    if len(basis) > 240:
        raise SystemExit(f"decision_basis too long ({len(basis)}): {basis}")
    out = {
        "n": n,
        "decision_basis": basis,
        "tool_call": {"name": name, "args": args},
        "observation": obs,
    }
    if reflection:
        out["reflection"] = reflection
    return out


def bash(n: int, basis: str, cmd: str, obs: str, reflection: str | None = None) -> dict:
    return step(n, basis, "bash", {"command": cmd}, obs, reflection)


def read(n: int, basis: str, path: str, obs: str) -> dict:
    return step(n, basis, "read", {"path": path}, obs)


def edit(n: int, basis: str, path: str, old: str, new: str, obs: str, reflection: str | None = None) -> dict:
    return step(n, basis, "edit", {"path": path, "old": old, "new": new}, obs, reflection)


def grep(n: int, basis: str, path: str, pattern: str, obs: str) -> dict:
    return step(n, basis, "grep", {"path": path, "pattern": pattern}, obs)


def assert_clean(ep: dict) -> None:
    blob = json.dumps(ep, ensure_ascii=True).lower()
    for needle in BANNED_NEEDLES:
        if needle.lower() in blob:
            raise SystemExit(f"{ep['id']} contains banned needle {needle!r}")
    for key in BANNED_KEYS:
        if key in ep:
            raise SystemExit(f"{ep['id']} top-level banned key {key}")
        for st in ep.get("steps", []):
            if key in st:
                raise SystemExit(f"{ep['id']} step banned key {key}")
    n = len(ep["steps"])
    if n < 16 or n > 18:
        raise SystemExit(f"{ep['id']} has {n} steps, want 16-18")
    if ep["meta"]["generator"] != GEN:
        raise SystemExit("bad generator")
    if "vessel" in ep["id"]:
        raise SystemExit(f"vessel id: {ep['id']}")


