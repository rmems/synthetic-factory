def main() -> None:
    waves = ((19, S19, L19), (20, S20, L20), (21, S21, L21), (22, S22, L22))
    for n, S, L in waves:
        stems = [r[1] for r in S] + [r[1] for r in L]
        if len(stems) != len(set(stems)):
            dups = [x for x in stems if stems.count(x) > 1]
            raise SystemExit(f"dup stems wave {n}: {sorted(set(dups))}")
        slugs = [r[0] for r in S] + [r[0] for r in L]
        if len(slugs) != len(set(slugs)):
            raise SystemExit(f"dup names wave {n}")
        for name, *_ in S + L:
            if any(tok in name for tok in ("html", "png", "svg", "matplotlib", "plotly", "dnsmasq")):
                raise SystemExit(f"viz token in {n} {name}")
        g.write_wave(n, S, L)
    print("wrote mills 19-22")


if __name__ == "__main__":
    main()
