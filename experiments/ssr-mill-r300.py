def _assert_catalog() -> None:
    slugs = [p["slug"] for pair in PAIRS for p in pair]
    if len(slugs) != len(set(slugs)):
        raise SystemExit("duplicate slugs in r300 catalog")
    tokens = [p["token"] for pair in PAIRS for p in pair]
    if len(tokens) != len(set(tokens)):
        raise SystemExit("duplicate tokens in r300 catalog")
    if any(len(p["decision_basis"]) > 240 for pair in PAIRS for p in pair for p in []):
        raise SystemExit("unreachable")
    for pair in PAIRS:
        for spec in pair:
            basis = spec["map_b"]
            if len(basis) > 240:
                raise SystemExit(f"map_b too long for {spec['slug']}: {len(basis)}")
            if len(spec["wrong_b"]) > 240:
                raise SystemExit(f"wrong_b too long for {spec['slug']}")


_assert_catalog()


def notes_md(rnd, suc, fail, suc_ep, fail_ep):
    coverage = max(52, 74 - (rnd - CATALOG_FIRST))
