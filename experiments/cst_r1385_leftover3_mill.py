def txn(args: list[str]) -> dict:
    cmd = [sys.executable, str(Path(__file__).resolve().parents[0] / "round_txn.py"), *args]
    out = subprocess.check_output(cmd, text=True)
    return json.loads(out)


def publish_round(rnd: int, pair: dict) -> tuple[str, str]:
    res = txn(["reserve", str(FACTORY), "--round", str(rnd), "--expected", "2"])
    staging = Path(res["staging_dir"])
    batch = staging / res["batch_file"]
    notes_f = staging / res["notes_file"]
    token = res["token"]
    ok = ep_ok(rnd, pair["slug_ok"], pair["ok"])
    bad = ep_bad(rnd, pair["slug_bad"], pair["bad"])
    batch.write_text(json.dumps(ok, separators=(",", ":")) + "\n" + json.dumps(bad, separators=(",", ":")) + "\n")
    notes_f.write_text(notes(rnd, pair, ok["id"], bad["id"]))
    pub = txn(["publish", str(FACTORY), "--round", str(rnd), "--token", token])
    if pub.get("records") != 2:
        raise SystemExit(f"publish failed r{rnd}: {pub}")
    return ok["id"], bad["id"]


def main() -> None:
    start = int(sys.argv[1]) if len(sys.argv) > 1 else 1385
    n = int(sys.argv[2]) if len(sys.argv) > 2 else 16
    offset = int(sys.argv[3]) if len(sys.argv) > 3 else 0
    published = []
    for i in range(n):
        rnd = start + i
        a, b = publish_round(rnd, PLANTS[offset + i])
        published.append((rnd, a, b))
        print(f"published r{rnd} {a} {b}", flush=True)
    print("DONE", len(published))


if __name__ == "__main__":
    main()
