def notes_for(round_number: int, recs: list) -> str:
    novel = 95.0 + min(1.5, 0.02 * max(0, round_number - START))
    lines = [
        f"# data-pipeline-repair-factory — NOTES r{round_number}",
        "",
        f"Novel coverage: {novel:.1f}%",
        "",
        "## Episodes",
    ]
    for rec in recs:
        steps = rec["steps"]
        success = rec["reward"]["success"]
        meta = rec["meta"]
        plan_step = next(
            (
                s
                for s in steps
                if str(s.get("decision_basis", "")).startswith("Reflection: Plan change")
            ),
            steps[11] if len(steps) > 11 else steps[-1],
        )
        lines.append(
            f"- `{rec['id']}`: {len(steps)} steps, success={success}, "
            f"domain={meta['domain']}, seed={meta['seed']}"
        )
        n_429 = next((s["n"] for s in steps if "429" in str(s.get("observation", ""))), "?")
        n_502 = next((s["n"] for s in steps if "502" in str(s.get("observation", ""))), "?")
        recov_429 = n_429 + 1 if isinstance(n_429, int) else "?"
        recov_502 = n_502 + 1 if isinstance(n_502, int) else "?"
        lines.append(
            f"  - 502 at step {n_502} recovered {recov_502}; "
            f"429 at step {n_429} recovered {recov_429}"
        )
        pc = plan_step.get("decision_basis", "")
        if pc.startswith("Reflection: "):
            pc = pc[len("Reflection: ") :]
        lines.append(f"  - plan change at step {plan_step['n']}: {pc}")
        lines.append("  - edit→test→fail→re-read→fix at steps 10-13")
    ok = [r["id"] for r in recs if r["reward"]["success"]]
    bad = [r["id"] for r in recs if not r["reward"]["success"]]
    lines += [
        "",
        "## decision_basis audit",
        "Every step has decision_basis starting with Plan:/Observation:/Reflection:/Tool call:, "
        "length ≤240, no thought/chain_of_thought/scratch/inner_monologue keys, no spike_events, "
        "no sim_or_real real, no Spikenaut. Generator grok-4.6. IDs are dpr-rN-<slug> without "
        "-wNNNN gum suffix. Goals have no [variant …] stamp and no fixture 2026-08-17 mill.",
        "",
        "## Mix",
        f"Success: {ok}. Realistic failure/handoff: {bad}.",
        "",
        "## Realism / weak recovery paths",
        "Noise recoveries are backoff+retry or local fixture cache. First patches are "
        "domain-plausible and fail closed. Designed traces — not live executions. Unique "
        "plants; not clones of r2248–r2630, gum r2254–r2262, Spark STRING watermark vs "
        "Santiago DST, Glue bookmark vs S3 etag, Iceberg expire-snapshots, Thanos compact, "
        "r2630 kaniko leftover, or r2374 nsq-ephem-disk / mqtt-retained.",
        "",
        "## Step counts",
    ]
    for rec in recs:
        lines.append(f"- {rec['id']}: {len(rec['steps'])} (required 16–17)")
    lines.append("")
    return "\n".join(lines)


def published_identities() -> set[str]:
    found: set[str] = set()
    if not FACTORY_DIR.is_dir():
        return found
    for path in FACTORY_DIR.glob("NOTES-r*.md"):
        text = path.read_text(errors="ignore").lower()
        for mx in re.finditer(r"domain=([a-z0-9._-]+)", text):
            found.add(mx.group(1))
        for mx in re.finditer(r"`(dpr-r\d+-[a-z0-9-]+)`", text):
            found.add(mx.group(1))
            found.add(re.sub(r"^dpr-r\d+-", "", mx.group(1)))
    for path in FACTORY_DIR.glob("batch-r*.jsonl"):
        try:
            lines = path.read_text(errors="ignore").splitlines()
        except OSError:
            continue
        for line in lines:
            if not line.strip():
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            i = str(rec.get("id") or "")
            if i.startswith("dpr-"):
                found.add(i.lower())
                found.add(re.sub(r"^dpr-r\d+-", "", i).lower())
            meta = rec.get("meta") or {}
            if meta.get("domain"):
                found.add(str(meta["domain"]).lower())
            if meta.get("seed"):
                found.add(str(meta["seed"]).lower())
    return found


def guard(spec: dict) -> None:
    blob = " ".join(
        str(spec.get(k, "")) for k in ("slug", "domain", "stack", "seed", "goal")
    ).lower()
    for needle in BANNED_NEEDLES:
        if needle.lower() in blob:
            raise SystemExit(f"banned needle {needle!r} in {spec.get('slug')}")


