def episode(rnd: int, spec: dict, *, success: bool, nsteps: int) -> dict:
    eid = f"iac-r{rnd}-{spec['slug']}"
    steps = success_steps(spec, nsteps) if success else fail_steps(spec, nsteps)
    if success:
        reward = {
            "success": True,
            "apply_fails": 1,
            "plan_changes": 1,
            "tests_passed": 2,
            "cost_steps": len(steps),
        }
    else:
        reward = {
            "success": False,
            "apply_fails": 1,
            "plan_changes": 1,
            "tests_passed": 1,
            "tests_failed": 1,
            "handoff": 1,
            "cost_steps": len(steps),
        }
    rec = {
        "id": eid,
        "goal": spec["goal"],
        "plan": spec["plan"],
        "steps": steps,
        "outcome": spec["outcome"],
        "reward": reward,
        "meta": {"factory": FACTORY, "round": rnd, "generator": GEN},
    }
    blob = json.dumps(rec)
    for key in BANNED:
        if f'"{key}"' in blob:
            raise SystemExit(f"{eid} contains banned key {key}")
    if "sim_or_real" in blob and '"real"' in blob:
        raise SystemExit(f"{eid} sim_or_real real")
    if not (12 <= len(steps) <= 18):
        raise SystemExit(f"{eid} {len(steps)} steps")
    return rec


