def clip(text: str, n: int = 240) -> str:
    text = " ".join(text.split())
    if len(text) <= n:
        return text
    return text[: n - 1].rstrip() + "…"


def step(n: int, basis: str, cmd: str, obs: str, *, name: str = "bash", **extra) -> dict:
    basis = clip(basis)
    prefix = basis.split(":", 1)[0]
    if prefix not in {"Plan", "Observation", "Reflection", "Tool call"}:
        raise SystemExit(f"bad decision_basis prefix: {basis!r}")
    if name == "bash":
        tool = {"name": "bash", "args": {"command": cmd}}
    elif name == "read":
        tool = {"name": "read", "args": {"path": cmd}}
    elif name == "edit":
        tool = {
            "name": "edit",
            "args": {"path": extra["path"], "old": extra["old"], "new": extra["new"]},
        }
    else:
        raise SystemExit(name)
    return {"n": n, "decision_basis": basis, "tool_call": tool, "observation": obs}


