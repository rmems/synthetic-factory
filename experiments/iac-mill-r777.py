def k8s_pair(
    s: str,
    g: str,
    m: str,
    product: str,
    kind: str,
    resource: str,
    api: str,
    ns: str,
    old: str,
    oldj: str,
    cur: str,
    field: str,
    fail: str,
) -> tuple[dict, dict]:
    nsf = f"-n {ns} " if ns else ""
    fq = f"{resource}.{api}" if api else resource
    ann = api if api else "infra.example.io"
    jpath = "{" + field + "}"
    fs = s.replace("-vs-old", "-old-leftover")
    leaf = field.rsplit(".", 1)[-1]
    fix_cmd = (
        f"kubectl {nsf}annotate {resource} web {ann}/current={cur} --overwrite"
        f" && kubectl {nsf}apply -f {resource}-web.yaml 2>&1 | tail -n 8"
    )
    fix_obs = f"{fq}/web configured\nReady True {leaf}={cur}\n"
    handoff = f"annotate {resource} jobs {ann}/current={cur}"
    return leftover_pair(
        s=s,
        fs=fs,
        g=g,
        m=m,
        t=f"{g}-web leftover {kind} {old}",
        ft=f"{g}-jobs leftover {kind} {oldj}",
        goal=(
            f"Repair designed plant {g}-prod {product}: leftover {kind} {old} still "
            f"selected by {resource} web. Pin current {kind} (do not kubectl delete "
            f"{resource} --force). Land apply + fixtures."
        ),
        fgoal=(
            f"{g}-jobs leftover {kind} {oldj} still selected in designed plant "
            f"{g}-prod. Stop kubectl delete {resource} --force. Handoff pin current {kind}."
        ),
        plan=f"Prove leftover {kind}; apply {resource}; fixtures.",
        fplan=f"Show leftover {kind}; first wrong delete {resource}; hand off.",
        lc=f"kubectl {nsf}get {resource}; kubectl {nsf}get {resource} web -o jsonpath='{jpath}'",
        lo=f"{cur}   Ready\n{old} leftover NotReady leftover_ref\n{old} leftover\n",
        ro=(
            f"def test_ref():\n    assert k8s.{m}('web').ref != '{old}'\n"
            f"def test_ready():\n    assert k8s.{m}('web').ready\n"
        ),
        ac=f"kubectl {nsf}apply -f {resource}-web.yaml 2>&1 | tail -n 10",
        af=f"Error: cannot apply {kind} web: leftover {kind} {old} {fail}\n",
        wb=f"Observation: leftover {old}. First wrong: kubectl delete {resource} --force.",
        wc=f"kubectl {nsf}delete {resource} web --force --grace-period=0 2>&1 | tail -n 6",
        wo=f"{fq} \"web\" deleted\n# leftover {kind} still {old}; live {kind} gone\n",
        fb=f"Reflection: annotate {resource} to current {cur}; apply {resource}-web.yaml.",
        fc=fix_cmd,
        fo=fix_obs,
        a2c=f"kubectl {nsf}get {resource} web -o jsonpath='{jpath}'",
        a2o=f"{cur}\n",
        cio=f"kubectl delete {resource} web --force\n",
        cin=(
            f"kubectl apply -f {resource}-web.yaml\n"
            f"# leftover {kind} {old}: pin current; never force-delete {resource} under a live {kind}.\n"
        ),
        lfc=f"kubectl {nsf}get {resource} {old} 2>&1 | head",
        lfo=f"Error from server (NotFound): {fq} \"{old}\" not found\n",
        vc=f"kubectl {nsf}get {resource} web -o jsonpath='{{.status.conditions[?(@.type==\"Ready\")].status}}'",
        vo="True\n",
        sc=f"kubectl {nsf}get {resource} --no-headers | head",
        so=f"{cur}   2\n",
        ec=f"pytest tests/test_{g}_{m}.py -q",
        eo="..\n2 passed\n",
        dc=f"kubectl {nsf}get {resource} web -o jsonpath='{jpath}'",
        do=f"{cur}\n",
        out=(
            f"leftover {kind} {old} {fail}. force-delete {resource} left none. "
            f"Plan change: pin current {cur}. Ready; pytest 2/2."
        ),
        seed=f"{product} leftover {kind} {old} vs delete {resource}",
        fail=f"{kind} leftover {old} {fail}",
        left=f"{old} CR gone",
        term=f"success {kind} Ready 2/2",
        flc=f"kubectl {nsf}get {resource} {oldj} -o jsonpath='{{.metadata.name}}'",
        flo=f"{oldj} leftover\n",
        fro=(
            f"def test_ref():\n    assert k8s.{m}('jobs').ref != '{oldj}'\n"
            f"def test_ready():\n    assert k8s.{m}('jobs').ready\n"
        ),
        fac=f"kubectl {nsf}apply -f {resource}-jobs.yaml 2>&1 | tail -n 8",
        faf=f"Error: leftover {kind} {oldj} {fail}\n",
        fwb=f"Observation: leftover {oldj}. First wrong: kubectl delete {resource} --force.",
        fwc=f"kubectl {nsf}delete {resource} jobs --force --grace-period=0 2>&1 | tail -n 6",
        fwo=f"{fq} \"jobs\" deleted\n# leftover {kind} still {oldj}",
        ffb=f"Reflection: handoff pin current {kind}; do not force-delete {resource} under a live {kind}.",
        ffo=f"no {product} apply rights (platform {kind})",
        handoff=handoff,
        fcin=(
            f"# leftover {kind} {oldj}. Handoff: pin current {kind}. "
            f"never force-delete {resource} under a live {kind}.\n"
        ),
        flfc=f"kubectl {nsf}get {resource} jobs -o jsonpath='{jpath}'",
        flfo=f"Error from server (NotFound): {fq} \"jobs\" not found\n",
        fvc=f"kubectl {nsf}get {resource} {oldj} 2>&1 | head",
        fvo=f"{oldj} leftover NotReady\n",
        fso=f"leftover {kind} {oldj}; {resource} deleted\n",
        fout=(
            f"leftover {kind} {oldj}. force-delete left none. PARTIAL: tests 0/2. "
            f"Handoff pin current {kind}; never force-delete {resource} under a live {kind}."
        ),
        fseed=f"leftover {product} {kind} {oldj}",
        ffail=f"{resource} gone; {kind} leftover {oldj}",
        fleft=f"{oldj} leftover",
        fterm=f"partial {m} {kind} handoff",
    )


