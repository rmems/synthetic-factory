def _trim(s: str, n: int = 240) -> str:
    s = " ".join(s.split())
    return s if len(s) <= n else s[: n - 1]


def gitcfg(
    *,
    slug: str,
    repo: str,
    marker: str,
    old: str,
    new: str,
    stem: str,
    key: str,
    bad: str,
    good: str | None,
    effect: str,
    probe: str,
    bad_obs: str,
    good_obs: str,
    wrong: str,
    wrong_obs: str,
    handoff: str | None = None,
    issue_t: str | None = None,
    ci_obs: str | None = None,
    kind: str = "config",
) -> dict:
    knob = f"{key}={bad}"
    if kind == "env":
        recover = f"Unset leftover {key}"
        map_cmd = f"echo {key}=${key}; {probe}; rg {marker} src/{stem}.py"
        rec_cmd = f"unset {key} && {probe}"
        left_cmd = f"echo {key}=${{{key}-unset}}"
        left_obs = f"{key}=unset"
        map_obs = f"{key}={bad}\n{bad_obs}\n{marker} = {old}"
    elif good is None:
        recover = f"Unset leftover {key}"
        map_cmd = f"git config --get {key}; {probe}; rg {marker} src/{stem}.py"
        rec_cmd = f"git config --unset {key} && {probe}"
        left_cmd = f"git config --get {key}; echo exit:$?"
        left_obs = "exit:1"
        map_obs = f"{bad}\n{bad_obs}\n{marker} = {old}"
    else:
        recover = f"Set leftover {key} to {good}"
        map_cmd = f"git config --get {key}; {probe}; rg {marker} src/{stem}.py"
        rec_cmd = f"git config {key} '{good}' && {probe}"
        left_cmd = f"git config --get {key}"
        left_obs = good
        map_obs = f"{bad}\n{bad_obs}\n{marker} = {old}"
    mix = f"leftover {knob} {effect}"
    w0 = wrong.split("&&")[0].strip()[:80]
    map_b = _trim(f"Plan: map leftover {knob}.")
    wrong_b = _trim(f"Observation: leftover {knob} survived. First wrong move: {w0}.")
    rec_b = _trim(f"Plan: {recover}.")
    if handoff:
        left_b = _trim(f"Observation: local leftover {knob} recovered; CI still set.")
        refl = _trim(
            f"Reflection: leftover {knob} survived. Plan change: PR the {new}; hand off CI."
        )
        return leftover_plant(
            slug=slug,
            repo=repo,
            marker=marker,
            old=old,
            new=new,
            stem=stem,
            knob=knob,
            effect=effect,
            mix=mix,
            map_cmd=map_cmd,
            map_obs=map_obs,
            map_b=map_b,
            wrong_cmd=wrong,
            wrong_obs=wrong_obs,
            wrong_b=wrong_b,
            rec_cmd=rec_cmd,
            rec_obs=good_obs,
            rec_b=rec_b,
            left_cmd=left_cmd,
            left_obs=left_obs,
            left_b=left_b,
            recover=recover,
            refl=refl,
            handoff=handoff,
            issue_t=issue_t or f"CI leftover still sets {knob}",
            issue_b=f"PR {{pr}}. Fix leftover {key} on CI. INC-{{inc}}.",
            handoff_probe=f"ssh ci-runner 'git config --global --get {key} || echo {key}=${key}'",
            handoff_probe_obs=ci_obs or bad,
            checks=f"unit pass\n{stem}-ci fail ({key})\n{{\"mergeStateStatus\":\"BLOCKED\"}}",
        )
    left_b = _trim(f"Observation: leftover {knob} recovered.")
    refl = _trim(
        f"Reflection: leftover {knob} survived. Plan change: recover/{stem}-{new}."
    )
    return leftover_plant(
        slug=slug,
        repo=repo,
        marker=marker,
        old=old,
        new=new,
        stem=stem,
        knob=knob,
        effect=effect,
        mix=mix,
        map_cmd=map_cmd,
        map_obs=map_obs,
        map_b=map_b,
        wrong_cmd=wrong,
        wrong_obs=wrong_obs,
        wrong_b=wrong_b,
        rec_cmd=rec_cmd,
        rec_obs=good_obs,
        rec_b=rec_b,
        left_cmd=left_cmd,
        left_obs=left_obs,
        left_b=left_b,
        recover=recover,
        refl=refl,
    )


