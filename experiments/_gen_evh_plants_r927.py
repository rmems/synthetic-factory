def main() -> None:
    orig_left = set(leftovers)
    rows = []
    seen_s, seen_d, seen_l = set(), set(), set()
    for i, raw in enumerate(RAW):
        n = 72 + i // 10
        ok_p = f"{POK[i % 10]}-{n}"
        bad_p = f"{PBAD[i % 10]}-{n}"
        ok_slug, ok_dom, lok, fok, xok, bad_slug, bad_dom, lbad, fbad, xbad, kind = raw
        for idx, tag, val in ((0, "hold leftover", lok), (1, "hold-dev leftover", lbad)):
            if val in orig_left or val in seen_l:
                val = f"{val}  # {tag}"
            if val in orig_left or val in seen_l:
                val = f"{val} {ok_slug if idx == 0 else bad_slug}"
            if idx == 0:
                lok = val
            else:
                lbad = val
            seen_l.add(val)
        blob = " ".join([ok_slug, bad_slug, lok, lbad, ok_p, bad_p]).lower()
        for w in THEME_BAN:
            if w in blob:
                raise SystemExit(f"THEME_BAN {w!r} in {ok_slug}")
        if ok_slug in slugs or ok_slug in seen_s:
            raise SystemExit(f"slug {ok_slug}")
        if bad_slug in slugs or bad_slug in seen_s:
            raise SystemExit(f"slug {bad_slug}")
        if ok_dom in domains or ok_dom in seen_d:
            raise SystemExit(f"dom {ok_dom}")
        if bad_dom in domains or bad_dom in seen_d:
            raise SystemExit(f"dom {bad_dom}")
        seen_s.update([ok_slug, bad_slug])
        seen_d.update([ok_dom, bad_dom])
        plan_ok = f"replace leftover {ok_slug}; fail-closed on {ok_p}"
        if len(plan_ok) > 180:
            raise SystemExit(f"plan {ok_slug} {len(plan_ok)}")
        rows.append((ok_slug, ok_dom, bad_slug, bad_dom, ok_p, bad_p,
                     lok, lbad, fok, fbad, xok, xbad, kind))
    lines = [
        '"""Unique DeepEval/pytest eval-loop leftover plants r927+.',
        "",
        "Not mill_plants_w canary leftovers (r801–r926). BAN r800",
        "geval-steps-gate-stale / cgeval-name-gate-stale, r480 vector-remap /",
        "alloy-relabel, r319 ClearML uri / Aim hash, GEval-cache / test_ prefix,",
        "unicode leftover, r50–r252, r253–r293, r294–r319 cartesian,",
        "Faithfulness empty-ctx / ConversationalGEval last-turn /",
        "GEval temperature-seed, RAGAS/promptfoo/LangSmith/Braintrust/LlamaIndex.",
        '"""',
        "",
        "from mill_plants import PAIRS",
        "from mill_plants_s import eval_pair",
        "",
        "ROWS = [",
    ]
    for r in rows:
        body = ",\n        ".join(repr(x) for x in r)
        lines.append("    (")
        lines.append("        " + body + ",")
        lines.append("    ),")
    lines += [
        "]",
        "",
        f"assert len(ROWS) == {len(rows)}, len(ROWS)",
        "",
        "for i, row in enumerate(ROWS):",
        "    PAIRS.append(eval_pair(*row[:12], i + 446, row[12]))",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("wrote", OUT, "pairs", len(rows), "covers r927-r" + str(926 + len(rows)))


if __name__ == "__main__":
    main()
