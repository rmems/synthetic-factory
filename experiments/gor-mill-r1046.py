def plant(
    *,
    slug: str,
    repo: str,
    marker: str,
    old: str,
    new: str,
    stem: str,
    mix: str,
    map_cmd: str,
    map_obs: str,
    map_b: str,
    wrong_cmd: str,
    wrong_obs: str,
    wrong_b: str,
    rec_cmd: str,
    rec_obs: str,
    rec_b: str,
    left_cmd: str,
    left_obs: str,
    left_b: str,
    goal: str,
    plan: str,
    out: str,
    refl: str,
    cmt: str,
    title: str,
    body: str,
    commit: str,
    handoff: str | None = None,
    issue_t: str | None = None,
    issue_b: str | None = None,
    handoff_probe: str | None = None,
    handoff_probe_obs: str | None = None,
    checks: str | None = None,
) -> dict:
    spec = {
        "slug": slug,
        "repo": repo,
        "marker": marker,
        "old": old,
        "new": new,
        "src": f"src/{stem}.py",
        "test": f"tests/test_{stem}.py",
        "tfail": (
            f"FAILED tests/test_{stem}.py::test_{stem}_{new}\n"
            f"FAILED tests/test_{stem}.py::test_{stem}_recovered"
        ),
        "branch": f"recover/{stem}-{new}",
        "mix": mix,
        "map_cmd": map_cmd,
        "map_obs": map_obs,
        "map_b": map_b,
        "wrong_cmd": wrong_cmd,
        "wrong_obs": wrong_obs,
        "wrong_b": wrong_b,
        "rec_cmd": rec_cmd,
        "rec_obs": rec_obs,
        "rec_b": rec_b,
        "left_cmd": left_cmd,
        "left_obs": left_obs,
        "left_b": left_b,
        "goal": goal,
        "plan": plan,
        "out": out,
        "refl": refl,
        "cmt": cmt,
        "title": title,
        "body": body,
        "commit": commit,
    }
    if handoff:
        spec["handoff"] = handoff
        spec["issue_t"] = issue_t or f"Residual {handoff} after local recover"
        spec["issue_b"] = issue_b or "PR {pr}. Residual still blocks merge. INC-{inc}."
        spec["handoff_probe"] = handoff_probe or f"echo residual_{handoff}"
        spec["handoff_probe_obs"] = handoff_probe_obs or f"residual_{handoff}"
        spec["checks"] = checks or (
            "unit pass\n"
            f"{handoff}-ci fail (residual)\n"
            '{"mergeStateStatus":"BLOCKED"}'
        )
    return spec


