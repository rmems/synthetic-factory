def _published_slugs() -> set[str]:
    used: set[str] = set()
    if not FACTORY_DIR.exists():
        return used
    for path in FACTORY_DIR.glob("batch-r*.jsonl"):
        for line in path.read_text().splitlines():
            if not line.strip():
                continue
            rec = json.loads(line)
            match = re.match(r"gor-r\d+-(.+)$", rec.get("id", ""))
            if match:
                used.add(match.group(1))
    return used


