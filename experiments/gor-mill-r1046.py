def _assert_catalog() -> None:
    slugs: list[str] = []
    markers: list[str] = []
    repos: list[str] = []
    published = _published_slugs()
    for idx, pair in enumerate(PAIRS):
        if len(pair) != 2:
            raise SystemExit("pair must be success+handoff")
        if "handoff" not in pair[1]:
            raise SystemExit(f"{pair[1]['slug']} missing handoff")
        if "handoff" in pair[0]:
            raise SystemExit(f"{pair[0]['slug']} success spec has handoff")
        if pair[0]["slug"].split("-")[0] == pair[1]["slug"].split("-")[0] and pair[0]["repo"] == pair[1]["repo"]:
            raise SystemExit(f"sibling twin {pair[0]['slug']} / {pair[1]['slug']}")
        own_round = CATALOG_FIRST + idx
        own_published = FACTORY_DIR.joinpath(f"batch-r{own_round}.jsonl").exists()
        for spec in pair:
            slugs.append(spec["slug"])
            markers.append(spec["marker"])
            repos.append(spec["repo"])
            if spec["slug"] in BANNED_SLUGS:
                raise SystemExit(f"banned slug {spec['slug']}")
            if spec["slug"] in published and not own_published:
                raise SystemExit(f"clone of published slug {spec['slug']}")
            if spec["slug"].endswith("-leftover"):
                raise SystemExit(f"{spec['slug']} leftover suffix")
            if spec["goal"].startswith("[") or "wrap 46" in spec["goal"].lower():
                raise SystemExit(f"{spec['slug']} wrap prefix")
            if "leftover hid" in spec["goal"].lower():
                raise SystemExit(f"{spec['slug']} leftover-hid goal")
            for key in ("map_b", "wrong_b", "rec_b", "left_b", "refl"):
                _check_basis(spec[key], 0, spec["slug"])
            if "Plan change" not in spec["refl"]:
                raise SystemExit(f"{spec['slug']} refl missing Plan change")
    if len(slugs) != len(set(slugs)):
        raise SystemExit("duplicate slugs")
    if len(markers) != len(set(markers)):
        raise SystemExit("duplicate markers")
    if len(repos) != len(set(repos)):
        raise SystemExit("duplicate repos")


def pick_pair(round_n: int) -> tuple[int, dict, dict]:
    """Next unused unique pair. Do not index by stolen leftover rounds."""
    published = _published_slugs()
    batch_exists = (FACTORY_DIR / f"batch-r{round_n}.jsonl").exists()
    for idx, pair in enumerate(PAIRS):
        sa, sb = pair
        used = sa["slug"] in published or sb["slug"] in published
        if used and not batch_exists:
            continue
        if used and batch_exists:
            # Re-emit only if this batch already carries these slugs.
            text = (FACTORY_DIR / f"batch-r{round_n}.jsonl").read_text()
            if sa["slug"] in text and sb["slug"] in text:
                return idx, sa, sb
            continue
        return idx, sa, sb
    raise SystemExit(
        f"no unused unique pair for round {round_n} (catalog {len(PAIRS)} pairs)"
    )


def generate_round(round_n: int) -> tuple[list[dict], str]:
    idx, sa, sb = pick_pair(round_n)
    published = _published_slugs()
    batch_exists = (FACTORY_DIR / f"batch-r{round_n}.jsonl").exists()
    for spec in (sa, sb):
        if spec["slug"] in published and not batch_exists:
            raise SystemExit(f"clone of published slug {spec['slug']}")
    pr_a = PR0 + 2 * idx
    pr_b = PR0 + 2 * idx + 1
    issue = ISSUE0 + idx
    inc_a = f"{round_n}3"
    inc_b = f"{round_n}8"
    a = build_episode(round_n, sa, success=True, pr=pr_a, issue=None, inc=inc_a)
    b = build_episode(round_n, sb, success=False, pr=pr_b, issue=issue, inc=inc_b)
    banned = (
        "thought",
        "chain_of_thought",
        "scratch",
        "inner_monologue",
        "spike_events",
    )
    for ep in (a, b):
        blob = json.dumps(ep)
        for key in banned:
            if f'"{key}"' in blob:
                raise SystemExit(f"{ep['id']} contains banned key {key}")
        if "wrap 46" in blob.lower() or "wrap-46" in blob.lower():
            raise SystemExit(f"{ep['id']} wrap-46")
        if ep["goal"].startswith("["):
            raise SystemExit(f"{ep['id']} wrap prefix goal")
        if "sim_or_real" in blob and '"real"' in blob:
            if re.search(r'"sim_or_real"\s*:\s*"real"', blob):
                raise SystemExit(f"{ep['id']} sim_or_real real")
        if "INC-INC-" in blob:
            raise SystemExit(f"{ep['id']} double INC prefix")
        if not (12 <= len(ep["steps"]) <= 18):
            raise SystemExit(f"{ep['id']} {len(ep['steps'])} steps")
    if a["reward"]["success"] == b["reward"]["success"]:
        raise SystemExit("batch must mix success + partial")
    return [a, b], notes_for(round_n, a, b, sa, sb)


def write_round(round_n: int, staging: Path) -> None:
    eps, notes = generate_round(round_n)
    batch = staging / f"batch-r{round_n:02d}.jsonl"
    nfile = staging / f"NOTES-r{round_n:02d}.md"
    with batch.open("w") as handle:
        for ep in eps:
            handle.write(json.dumps(ep, ensure_ascii=True, separators=(",", ":")) + "\n")
    nfile.write_text(notes)
    print(f"wrote {batch} ({len(eps)} eps) {nfile}", file=sys.stderr)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--round", type=int, required=True)
    parser.add_argument("--staging", required=True)
    args = parser.parse_args()
    _assert_catalog()
    write_round(args.round, Path(args.staging))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
