def _sha(slug: str) -> str:
    h = hashlib.sha1(f"gor-{slug}".encode()).hexdigest()[:7]
    if h == "0000000" or not any(c.isalpha() for c in h):
        h = hashlib.sha1(f"gor-{slug}-x".encode()).hexdigest()[:7]
    return h


