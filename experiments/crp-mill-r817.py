def _used_from_disk() -> set[str]:
    used: set[str] = set()
    if not FACTORY_DIR.is_dir():
        return used
    fam_re = re.compile(r"family=`([^`]+)`")
    id_re = re.compile(r"`crp-r\d+-([^`]+)`")
    for path in FACTORY_DIR.glob("NOTES-r*.md"):
        text = path.read_text()
        used.update(fam_re.findall(text))
        used.update(id_re.findall(text))
    for path in FACTORY_DIR.glob("batch-r*.jsonl"):
        for line in path.read_text().splitlines():
            if not line.strip():
                continue
            rec = json.loads(line)
            rid = rec.get("id") or ""
            m = re.match(r"crp-r\d+-(.+)$", rid)
            if m:
                used.add(m.group(1))
            fam = (rec.get("meta") or {}).get("family")
            if fam:
                used.add(fam)
    return used


def _skip(plant: dict, used: set[str]) -> bool:
    fam = plant["family"]
    slug = plant["slug"]
    if fam in used or slug in used:
        return True
    blob = f"{fam} {slug}".lower()
    return any(s in blob for s in _SKIP_SUBSTR)


def unused_plants() -> list[dict]:
    used = _used_from_disk()
    return [p for p in PLANTS if not _skip(p, used)]


def plants_for_round(round_n: int) -> list[dict]:
    if round_n < 1:
        raise SystemExit(f"bad round {round_n}")
    unused = unused_plants()
    if len(unused) < 3:
        raise SystemExit(f"no unused plant triple for r{round_n} (left={len(unused)})")
    return unused[:3]


