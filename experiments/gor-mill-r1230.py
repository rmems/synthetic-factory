def _sha(eid: str) -> str:
    return hashlib.sha1(eid.encode()).hexdigest()[:7]


def _set_marker_cmd(src: str, marker: str, old: str, new: str) -> str:
    return (
        "python3 - <<'PY'\n"
        "from pathlib import Path\n"
        f"p=Path({src!r})\n"
        f"p.write_text(p.read_text().replace({marker!r} + ' = {old}', {marker!r} + ' = {new}'))\n"
        f"print({new!r})\n"
        "PY"
    )


