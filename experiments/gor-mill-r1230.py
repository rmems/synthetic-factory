def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--round", type=int, required=True)
    ap.add_argument("--pair", type=int, required=True)
    ap.add_argument("--staging-dir", type=Path, required=True)
    ap.add_argument("--notes", action="store_true")
    args = ap.parse_args()
    if args.pair < 0 or args.pair >= len(PAIRS):
        print("bad pair", file=sys.stderr)
        return 2
    a_spec, b_spec = PAIRS[args.pair]
    pr0 = 7300 + args.round * 2
    inc_a = f"INC-{args.round}3"
    inc_b = f"INC-{args.round}8"
    a = build_episode(args.round, a_spec, success=True, pr=pr0, issue=None, inc=inc_a)
    b = build_episode(args.round, b_spec, success=False, pr=pr0 + 1, issue=6900 + args.round, inc=inc_b)
    staging = args.staging_dir
    staging.mkdir(parents=True, exist_ok=True)
    batch = staging / f"batch-r{args.round}.jsonl"
    with batch.open("w") as f:
        f.write(json.dumps(a, separators=(",", ":")) + "\n")
        f.write(json.dumps(b, separators=(",", ":")) + "\n")
    if args.notes:
        (staging / f"NOTES-r{args.round}.md").write_text(notes_md(args.round, a, b, 53 + (args.pair % 4)))
    print(a["id"], b["id"], batch)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
