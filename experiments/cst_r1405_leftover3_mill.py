def _cmd(args: list[str]) -> dict:
    proc = subprocess.run(args, cwd=ROOT, capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError((proc.stderr or proc.stdout or f"exit {proc.returncode}").strip())
    out = proc.stdout.strip()
    return json.loads(out) if out else {}


def hop_unreserved() -> Path | None:
    base = ROOT / "outputs/raw/2026-08-19-agentic"
    for child in sorted(p for p in base.iterdir() if p.is_dir()):
        if child.name == "sandbox-refusal-factory":
            continue
        st = _cmd(TXN + ["frontier", str(child)])
        nxt = int(st["next_round"])
        if (child / f"ROUND-r{nxt:02d}.reserved.json").exists():
            continue
        return child
    return None


def publish_round(rnd: int, pair: dict) -> tuple[str, str]:
    res = txn(["reserve", str(FACTORY), "--round", str(rnd), "--expected", "2"])
    staging = Path(res["staging_dir"])
    batch = staging / res["batch_file"]
    notes_f = staging / res["notes_file"]
    token = res["token"]
    ok_ep = ep_ok(rnd, pair["slug_ok"], pair["ok"])
    bad_ep = ep_bad(rnd, pair["slug_bad"], pair["bad"])
    batch.write_text(
        json.dumps(ok_ep, separators=(",", ":")) + "\n" + json.dumps(bad_ep, separators=(",", ":")) + "\n"
    )
    notes_f.write_text(notes(rnd, pair, ok_ep["id"], bad_ep["id"]))
    pub = txn(["publish", str(FACTORY), "--round", str(rnd), "--token", token])
    if pub.get("records") != 2:
        raise SystemExit(f"publish failed r{rnd}: {pub}")
    return ok_ep["id"], bad_ep["id"]


def main() -> None:
    published = []
    failed_round = None
    fr = _cmd(TXN + ["frontier", str(FACTORY)])
    start = int(fr["next_round"])
    for i, pair in enumerate(PLANTS):
        if len(published) >= MAX_ROUNDS:
            break
        fr = _cmd(TXN + ["frontier", str(FACTORY)])
        rnd = int(fr["next_round"])
        try:
            a, b = publish_round(rnd, pair)
        except Exception as exc:
            failed_round = rnd
            print(f"reserve/publish failed round {failed_round}: {exc}", file=sys.stderr)
            hop = hop_unreserved()
            print(f"hop {hop}", file=sys.stderr)
            break
        published.append({"round": rnd, "ids": [a, b]})
        print(json.dumps({"published": rnd, "ids": [a, b]}), flush=True)
    print(json.dumps({"done": published, "failed_round": failed_round}, indent=2))


if __name__ == "__main__":
    main()
