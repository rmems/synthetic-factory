def write_round(round_n: int, staging: Path) -> list[str]:
    recs = [pair(p, round_n, i) for i, p in enumerate(plants_for_round(round_n))]
    batch = staging / f"batch-r{round_n:02d}.jsonl"
    notes = staging / f"NOTES-r{round_n:02d}.md"
    with batch.open("w") as handle:
        for rec in recs:
            handle.write(json.dumps(rec, ensure_ascii=False) + "\n")
    notes.write_text(notes_for(round_n, recs))
    return [r["id"] for r in recs]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--round", type=int, required=True)
    parser.add_argument("--staging", type=Path, required=True)
    args = parser.parse_args()
    ids = write_round(args.round, args.staging)
    print(json.dumps({"round": args.round, "ids": ids, "staging": str(args.staging)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
