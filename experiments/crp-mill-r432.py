def plants_for_round(round_n: int) -> list[dict]:
    idx = round_n - FIRST_ROUND
    if idx < 0:
        raise SystemExit(f"mill starts at r{FIRST_ROUND}, got r{round_n}")
    start = idx * 3
    chunk = PLANTS[start : start + 3]
    if len(chunk) != 3:
        raise SystemExit(f"no plant triple for r{round_n} (catalog {FIRST_ROUND}+{len(PLANTS)//3 - 1})")
    return chunk


