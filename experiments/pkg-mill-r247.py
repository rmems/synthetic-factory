BANNED_KEYS = ("thought", "chain_of_thought", "scratch", "inner_monologue", "spike_events")
BANNED_PHRASES = (
    "reuse-downloaded-gpl-license",
    "cdx-metadata-supplier",
    "digest equals git sha",
    "digest=git sha",
    "lockfile yank twin",
)


def banned_text(obj: dict) -> None:
    blob = json.dumps(obj)
    for key in BANNED_KEYS:
        if f'"{key}"' in blob:
            raise SystemExit(f"banned key present: {key}")
    if '"sim_or_real": "real"' in blob or '"sim_or_real":"real"' in blob:
        raise SystemExit("sim_or_real real banned")
    low = blob.lower()
    for phrase in BANNED_PHRASES:
        if phrase in low:
            raise SystemExit(f"banned phrase present: {phrase}")


def emit(round_n: int) -> tuple[dict, dict, str]:
    idx = round_n - CATALOG_FIRST
    if idx < 0 or idx >= len(PAIRS):
        raise SystemExit(f"round {round_n} outside catalog {CATALOG_FIRST}+{len(PAIRS)}")
    ok_kind, ok_spec, fail_kind, fail_spec = PAIRS[idx]
    ok_ep = BUILDERS[ok_kind](round_n, ok_spec)
    fail_ep = BUILDERS[fail_kind](round_n, fail_spec)
    banned_text(ok_ep)
    banned_text(fail_ep)
    return ok_ep, fail_ep, notes_for(round_n, ok_spec, fail_spec)


def selfcheck() -> None:
    slugs: list[str] = []
    plants: list[str] = []
    for i, (ok_kind, ok_spec, fail_kind, fail_spec) in enumerate(PAIRS):
        rnd = CATALOG_FIRST + i
        ok_ep, fail_ep, notes = emit(rnd)
        if "Novel coverage:" not in notes:
            raise SystemExit(f"r{rnd} notes missing Novel coverage")
        slugs.extend([ok_spec["slug"], fail_spec["slug"]])
        plants.extend([ok_spec["plant"], fail_spec["plant"]])
        if ok_kind not in BUILDERS or fail_kind not in BUILDERS:
            raise SystemExit(f"r{rnd} bad builder")
    if len(slugs) != len(set(slugs)):
        raise SystemExit(f"duplicate slugs: {[s for s in slugs if slugs.count(s) > 1]}")
    if len(plants) != len(set(plants)):
        raise SystemExit(f"duplicate plants: {[p for p in plants if plants.count(p) > 1]}")
    print(
        json.dumps(
            {
                "catalog_first": CATALOG_FIRST,
                "n_pairs": len(PAIRS),
                "last_round": CATALOG_FIRST + len(PAIRS) - 1,
                "slugs": slugs[:8],
            }
        )
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--round", type=int)
    parser.add_argument("--staging", type=Path)
    parser.add_argument("--selfcheck", action="store_true")
    args = parser.parse_args()
    if args.selfcheck:
        selfcheck()
        return 0
    if args.round is None or args.staging is None:
        raise SystemExit("need --round and --staging (or --selfcheck)")
    ok_ep, fail_ep, notes = emit(args.round)
    args.staging.mkdir(parents=True, exist_ok=True)
    batch = args.staging / f"batch-r{args.round:02d}.jsonl"
    notes_path = args.staging / f"NOTES-r{args.round:02d}.md"
    with batch.open("w") as handle:
        handle.write(json.dumps(ok_ep, ensure_ascii=False) + "\n")
        handle.write(json.dumps(fail_ep, ensure_ascii=False) + "\n")
    notes_path.write_text(notes)
    print(
        json.dumps(
            {
                "round": args.round,
                "ids": [ok_ep["id"], fail_ep["id"]],
                "steps": [len(ok_ep["steps"]), len(fail_ep["steps"])],
                "batch": str(batch),
                "notes": str(notes_path),
            }
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
