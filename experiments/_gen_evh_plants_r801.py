def with_plants(rows: list[tuple]) -> list[tuple]:
    out = []
    for i, r in enumerate(rows):
        n = 59 + i // 10
        ok_p = f"{PLANTED_OK[i % 10]}-{n}"
        bad_p = f"{PLANTED_BAD[i % 10]}-{n}"
        # r = slug,dom,slug,dom, leftover_ok, leftover_bad, first_ok, first_bad, fix_ok, fix_bad, kind
        out.append((
            r[0], r[1], r[2], r[3],
            ok_p, bad_p,
            r[4], r[5], r[6], r[7], r[8], r[9], r[10],
        ))
    return out


def check_bans(rows: list[tuple]) -> None:
    for r in rows:
        blob = " ".join(map(str, r)).lower()
        for w in THEME_BAN:
            if w in blob:
                raise SystemExit(f"THEME_BAN {w!r} in {r[0]}")
        text = " ".join(map(str, r))
        for s in BANNED_SNIPS:
            if s.startswith("U+") or "‧" in s:
                if s in text:
                    raise SystemExit(f"BANNED {s!r} in {r[0]}")
            elif s.lower() in blob:
                raise SystemExit(f"BANNED {s!r} in {r[0]}")


def main() -> None:
    slugs, domains, leftovers = used()
    orig_left = set(leftovers)
    rows = with_plants(catalog())
    # Disambiguate leftover snippets that already exist as first_old.
    seen_left: set[str] = set()
    fixed = []
    for r in rows:
        r = list(r)
        for idx, tag in ((6, "canary leftover"), (7, "canary-dev leftover")):
            if r[idx] in orig_left or r[idx] in seen_left:
                r[idx] = f"{r[idx]}  # {tag}"
            if r[idx] in orig_left or r[idx] in seen_left:
                r[idx] = f"{r[idx]} {r[0]}"
            seen_left.add(r[idx])
        fixed.append(tuple(r))
    rows = fixed
    leftovers = orig_left
    print("catalog pairs", len(rows))
    check_bans(rows)
    new_slugs = []
    new_doms = []
    new_left = []
    for r in rows:
        new_slugs += [r[0], r[2]]
        new_doms += [r[1], r[3]]
        new_left += [r[6], r[7]]
        if len(r[0]) > 70 or len(r[2]) > 70:
            raise SystemExit(f"slug too long {r[0]} {r[2]}")
        if len(r[1]) > 24 or len(r[3]) > 24:
            raise SystemExit(f"domain too long {r[1]} {r[3]}")
        plan_ok = f"replace leftover {r[0]}; fail-closed on {r[4]}"
