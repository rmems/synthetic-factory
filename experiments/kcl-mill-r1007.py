def guard(spec: dict) -> None:
    plant = spec["plant"]
    stem = plant[:-5] if plant.endswith("-prod") else plant
    if plant in BANNED_PLANTS or stem in BANNED_PLANTS:
        raise SystemExit(f"banned plant {plant}")
    if spec["slug"] in {"sx-handoff", "w3-empty"}:
        raise SystemExit("banned slug")
    identity = " ".join(
        str(spec.get(k, ""))
        for k in ("plant", "slug", "field", "fail_val", "fix_val")
    ).lower()
    for needle in BANNED_NEEDLES:
        if needle in identity:
            raise SystemExit(f"banned needle {needle!r} in identity {identity!r}")


