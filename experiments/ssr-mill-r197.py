def plant(
    *,
    slug: str,
    scanner: str,
    mechanic: str,
    repo: str,
    leak: str,
    extra: str,
    token: str,
    env: str,
    sha: str,
    pr: int,
    mix: str,
    scan_invoke: str,
    scan_hit: str,
    extra_line: str,
    miss_cmd: str,
    miss_green: str,
    wrong_b: str,
    wrong_cmd: str,
    wrong_obs: str,
    hide_cmd: str | None = None,
    hide_obs: str | None = None,
    strip_obs: str | None = None,
    map_b: str | None = None,
    map_cmd: str | None = None,
    map_obs: str | None = None,
    extra_files: list[str] | None = None,
) -> dict:
    if slug in BANNED_SLUGS:
        raise SystemExit(f"banned slug: {slug}")
    if "TESTONLY_" not in token:
        raise SystemExit(f"token must contain TESTONLY_: {token}")
    if any(x in slug for x in ("cipher", "pulumi", "tfc-", "snyk", "netlify", "braintree", "adyen")):
        raise SystemExit(f"banned family in slug: {slug}")
    top = leak.split("/")[0]
    head_files = extra_files or [leak, extra]
    return {
        "slug": slug,
        "scanner": scanner,
        "mechanic": mechanic,
        "repo": repo,
        "leak": leak,
        "extra": extra,
        "head_files": head_files,
        "token": token,
        "env": env,
        "sha": sha,
        "pr": pr,
        "scan_cmd": (
            f"{scan_invoke} 2>&1 | tail -10; rg -n TESTONLY {leak} {extra} | head; "
            f"git log --oneline -- {leak} | head"
        ),
        "scan_obs": (
            f"{scan_hit}\n{leak}: {env}={token}\n{extra}: {extra_line}\n{sha} add {leak}"
        ),
        "map_b": map_b or f"Observation: {scanner} miss via {mechanic}.",
        "map_cmd": map_cmd or f"{miss_cmd}; rg -n TESTONLY {leak} | head",
        "map_obs": map_obs or f"{miss_green}\n{env}={token}",
        "wrong_b": wrong_b if wrong_b.startswith("Plan:") else f"Plan: first apply - {wrong_b}",
        "wrong_cmd": wrong_cmd,
        "wrong_obs": wrong_obs,
        "hide_cmd": hide_cmd or f"echo '{top}/' >> .gitignore; rg TESTONLY {leak} | head",
        "hide_obs": hide_obs or f"{env}={token}  (still indexed)",
        "strip_obs": strip_obs or f"{env} via env; {slug} is not a git fix",
        "mix": mix,
    }


