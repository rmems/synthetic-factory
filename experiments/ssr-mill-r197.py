def extend_success(ep: dict, spec: dict, rnd: int, n_steps: int) -> dict:
    token = spec["token"]
    leak = spec["leak"]
    sha = spec["sha"]
    scanner = spec["scanner"]
    slug = spec["slug"]
    purge = f"purge/{slug}"
    feat = f"feat/{slug}-purge"
    if n_steps >= 17 and len(ep["steps"]) < 17:
        ep["steps"].append(
            step(
                17,
                f"Observation: file rotate ticket for {token}; {purge} ready for cutover.",
                f"echo ticket=rotate-{slug} purge={purge} token={token}",
                f"ticket=rotate-{slug} purge={purge} token={token}",
            )
        )
    if n_steps >= 18 and len(ep["steps"]) < 18:
        ep["steps"].append(
            step(
                18,
                "Observation: origin/main still residual; do not force-push main.",
                f"echo no_force_push_main=1 residual={sha} scanner={scanner} leak={leak} feat={feat}",
                f"no_force_push_main=1 residual={sha} scanner={scanner} leak={leak} feat={feat}",
            )
        )
    for i, s in enumerate(ep["steps"], 1):
        s["n"] = i
    ep["reward"]["cost_steps"] = len(ep["steps"])
    return ep


