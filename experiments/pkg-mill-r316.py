PAIRS = _pairs()


def published_slugs() -> set[str]:
    out: set[str] = set()
    root = HERE.parent / "outputs" / "raw" / "2026-08-19-agentic" / "package-release-factory"
    for path in glob.glob(str(root / "batch-r*.jsonl")):
        with open(path) as handle:
            for line in handle:
                if not line.strip():
                    continue
                rec = json.loads(line)
                ident = rec.get("id", "")
                parts = ident.split("-", 2)
                if len(parts) == 3:
                    out.add(parts[2])
    return out


def emit(round_n: int, idx: int):
    if idx < 0 or idx >= len(PAIRS):
        raise SystemExit(f"idx {idx} outside catalog 0+{len(PAIRS)}")
    ok_kind, ok_spec, fail_kind, fail_spec = PAIRS[idx]
    published = published_slugs()
    for slug in (ok_spec["slug"], fail_spec["slug"]):
        if slug in published:
            raise SystemExit(f"clone of published slug {slug}")
    ok_ep = BUILDERS[ok_kind](round_n, ok_spec)
    fail_ep = BUILDERS[fail_kind](round_n, fail_spec)
    banned_text(ok_ep)
    banned_text(fail_ep)
    return ok_ep, fail_ep, notes_for(round_n, ok_spec, fail_spec)


def selfcheck():
    slugs, plants = [], []
    published = published_slugs()
    for i, (_, ok, _, fail) in enumerate(PAIRS):
        emit(CATALOG_FIRST + i, i)
        slugs += [ok["slug"], fail["slug"]]
        plants += [ok["plant"], fail["plant"]]
        for slug in (ok["slug"], fail["slug"]):
            if slug in published:
                raise SystemExit(f"clone of published slug {slug}")
    if len(slugs) != len(set(slugs)) or len(plants) != len(set(plants)):
        raise SystemExit("dup")
    print(json.dumps({"n_pairs": len(PAIRS), "slugs": slugs[:4]}))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--round", type=int)
    parser.add_argument("--idx", type=int)
    parser.add_argument("--staging", type=Path)
    parser.add_argument("--selfcheck", action="store_true")
    args = parser.parse_args()
    if args.selfcheck:
        selfcheck()
        return 0
    if args.idx is None:
        raise SystemExit("--idx required")
    ok_ep, fail_ep, notes = emit(args.round, args.idx)
    args.staging.mkdir(parents=True, exist_ok=True)
    batch = args.staging / f"batch-r{args.round:02d}.jsonl"
    notes_path = args.staging / f"NOTES-r{args.round:02d}.md"
    with batch.open("w") as handle:
        handle.write(json.dumps(ok_ep, ensure_ascii=False) + "\n")
        handle.write(json.dumps(fail_ep, ensure_ascii=False) + "\n")
    notes_path.write_text(notes)
    print(
        json.dumps(
            {
                "round": args.round,
                "idx": args.idx,
                "ids": [ok_ep["id"], fail_ep["id"]],
                "steps": [len(ok_ep["steps"]), len(fail_ep["steps"])],
            }
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
