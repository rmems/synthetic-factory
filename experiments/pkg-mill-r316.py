def banned_text(obj: dict) -> None:
    blob = json.dumps(obj)
    for key in base.BANNED_KEYS:
        if f'"{key}"' in blob:
            raise SystemExit(f"banned key present: {key}")
    if '"sim_or_real": "real"' in blob or '"sim_or_real":"real"' in blob:
        raise SystemExit("sim_or_real real banned")
    low = blob.lower()
    for phrase in BANNED_PHRASES:
        if phrase in low:
            raise SystemExit(f"banned phrase present: {phrase}")


def okd(**kw):
    ver = kw.pop("ver")
    fix_path = kw["fix_path"]
    change = kw["change"]
    kw.setdefault("tag_cmd", f"git verify-tag v{ver} >/dev/null && echo signed_tag_ok")
    kw.setdefault("tag_obs", "signed_tag_ok")
    kw.setdefault("cmt_cmd", f"git add {fix_path} && git commit -m '{change}; leftover note'")
    kw.setdefault("cmt_obs", "[main " + hx(kw["slug"] + "-cmt", 7) + f"] {change}; leftover note")
    return _ok(**kw)


def faild(**kw):
    return _fail(**kw)


