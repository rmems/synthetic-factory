def contract_ok(ep: dict) -> list[str]:
    errs = []
    steps = ep["steps"]
    if not (8 <= len(steps) <= 16):
        errs.append(f"{ep['id']}: {len(steps)} steps")
    names = {s["tool_call"]["name"] for s in steps}
    if len(names) < 3:
        errs.append(f"{ep['id']}: {len(names)} tool types")
    blob = json.dumps(ep)
    hosts = sorted(set(re.findall(r"https://([a-z0-9.-]+\.example)", blob)))
    if len(hosts) < 3:
        errs.append(f"{ep['id']}: {len(hosts)} hosts {hosts}")
    if not any("Error:" in s["observation"] or re.search(r"\b[45]\d\d\b", s["observation"]) for s in steps):
        errs.append(f"{ep['id']}: no failed tool")
    for need in ("browser_screenshot", "browser_fill_form", "browser_click"):
        if need not in names:
            errs.append(f"{ep['id']}: missing {need}")
    for banned in ("thought", "chain_of_thought", "scratch", "inner_monologue", "spike_events"):
        if f'"{banned}"' in blob:
            errs.append(f"{ep['id']}: banned key {banned}")
    return errs


def spec_for_round(rnd: int) -> dict:
    idx = rnd - CATALOG_FIRST
    if idx < 0 or idx >= len(PAIRS):
        raise SystemExit(f"no plant for r{rnd} (catalog {CATALOG_FIRST}+{len(PAIRS)})")
    return PAIRS[idx]


def build_round(rnd: int) -> tuple[list[dict], str]:
    spec = spec_for_round(rnd)
    if spec["prefix"] == spec["aux"] or spec["prefix"] == "api" or spec["aux"] == "api":
        raise SystemExit(f"r{rnd}: prefix/aux/api must be distinct ({spec['prefix']!r} {spec['aux']!r})")
    eps = [success_episode(rnd, spec), fail_episode(rnd, spec)]
    errs: list[str] = []
    for ep in eps:
        errs.extend(contract_ok(ep))
    if USED_HOSTS.exists():
        used = set(USED_HOSTS.read_text().split())
        for ep in eps:
            for h in re.findall(r"https://([a-z0-9.-]+\.example)", json.dumps(ep)):
                if h in used:
                    errs.append(f"reused host {h}")
    if USED_PLACES.exists():
        used_p = set(USED_PLACES.read_text().split())
        for p in (spec["ok_place"], spec["bad_place"]):
            if p in used_p:
                errs.append(f"reused place {p}")
    if errs:
        raise SystemExit("contract:\n" + "\n".join(errs))
    return eps, notes_for(rnd, spec)


def write_stage(stage: Path, rnd: int, eps: list[dict], notes: str) -> None:
    (stage / f"batch-r{rnd:02d}.jsonl").write_text("".join(json.dumps(ep, ensure_ascii=False) + "\n" for ep in eps))
    (stage / f"NOTES-r{rnd:02d}.md").write_text(notes)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--round", type=int, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    eps, notes = build_round(args.round)
    write_stage(args.out, args.round, eps, notes)
    print(json.dumps({"round": args.round, "ids": [e["id"] for e in eps], "bytes": sum(len(json.dumps(e)) for e in eps)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
